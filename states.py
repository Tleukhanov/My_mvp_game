class Hierarchy:
    """Менеджер владений: экономика, контракты, мнение, конец хода.

    Работает со списком провинций-объектов (duck typing) и с тремя
    словарями-реестрами. Ничего не знает про pygame и про отрисовку.

    Про ГПСЧ. Потоки лежат на объекте, и **ни один тик их не трогает**: ни
    ``tick_counties``, ни ``tick_vassals``, ни ``tick_realms``, ни
    ``resolve_orders``, ни ``end_turn`` не делают ни одного броска. Это
    осознанное ограничение, а не забывчивость — иначе тесты детерминизма
    разошлись бы по хешу. Решение вассала по приказу тоже не бросает кубик: оно
    выведено из мнения через ``can_accept_order``, поэтому два одинаковых мира
    после одинаковой последовательности приказов совпадут до бита. Единственное
    место, где бросок допустим, — явная команда, в которой игрок сам попросил
    случайность: ``hire_mercenaries`` (тир наёмника). Поэтому ``streams``
    можно не передавать: дефолтный набор потоков не влияет на состояние мира.
    """

    def __init__(
        self,
        provinces: Sequence,
        duchies: Optional[Dict[str, Duchy]] = None,
        realms: Optional[Dict[str, Realm]] = None,
        characters: Optional[Dict[str, Character]] = None,
        contracts: Optional[Dict[str, VassalContract]] = None,
        streams: Optional[NamedStreams] = None,
        *,
        orders: Optional[Dict[str, Order]] = None,
        succession_crises: Optional[Dict[str, SuccessionCrisis]] = None,
    ):
        self.provinces = provinces
        self.duchies: Dict[str, Duchy] = duchies if duchies is not None else {}
        self.realms: Dict[str, Realm] = realms if realms is not None else {}
        self.characters: Dict[str, Character] = characters if characters is not None else {}
        #: ключ — id вассала, значение — контракт с сюзереном.
        self.contracts: Dict[str, VassalContract] = contracts if contracts is not None else {}
        #: именованные потоки ГПСЧ. ВНЕШНИЙ источник энтропии: снапшот
        #: его не содержит (см. ``to_state``), при восстановлении потоки
        #: задаются заново конструктором.
        self.streams: NamedStreams = streams if streams is not None else new_streams(
            HIERARCHY_DEFAULT_SEED)
        self.turn: int = 1
        self.log: List[str] = []
        #: True, если журнал хоть раз упирался в ``LOG_KEEP``. Хранится в
        #: состоянии, а не вычисляется по ``len(self.log)``, иначе снапшот
        #: после round-trip выглядел бы иначе, чем до него.
        self.log_truncated: bool = False
        #: Журнал израсходованных за ход действий: ключ
        #: ``f"{turn}:{actor}:{action}"`` -> сколько раз уже выполнено.
        #: Живёт на объекте, а не в снапшоте — см. длинное объяснение в
        #: ``to_state``: каноническая точка сохранения — граница хода, а
        #: ``end_turn`` обнуляет журнал, поэтому в снапшоте он всегда пуст.
        self.action_ledger: Dict[str, int] = {}
        #: Выданные приказы по id. В отличие от ``log`` это СОСТОЯНИЕ, а не
        #: история: у приказа есть срок и последствия, поэтому он обязан
        #: пережить ``end_turn``, попасть в снапшот и в ``state_hash``.
        #: Записи не удаляются никогда — на этом держится счётчик id
        #: (``len(self.orders)``), см. ``_next_order_id``.
        self.orders: Dict[str, Order] = orders if orders is not None else {}
        #: Открытые и закрытые кризисы престола по id королевства (этап 4).
        #: СОСТОЯНИЕ, а не история: пустой трон виден игроку и обязан пережить
        #: ``end_turn``, поэтому запись живёт в снапшоте и в ``state_hash``.
        #: Реестр не растёт — на королевство ровно одна запись.
        self.succession_crises: Dict[str, SuccessionCrisis] = (
            succession_crises if succession_crises is not None else {})
        self._province_duchy: Dict[int, str] = {}
        self._rebuild_province_index()


    # ---------------- журнал ----------------

    def _append_log(self, entries: Sequence[str]) -> None:
        """Дописать события в журнал, подрезав его до ``LOG_KEEP``."""
        self.log.extend(entries)
        if len(self.log) > LOG_KEEP:
            del self.log[:len(self.log) - LOG_KEEP]
            self.log_truncated = True

    # ---------------- журнал лимитов действий ----------------

    def _ledger_key(self, actor_id: str, action: str) -> str:
        """Ключ журнала: ``turn:actor:action``.

        Ход внутри ключа, а не в значении: журнал обнуляется в ``end_turn``,
        поэтому номер хода нужен только для читаемости логов сервера и для
        отладки. ``action`` может быть уточнён целью
        (``gift_vassal:baron_wolf``) — тогда лимит действует на пару
        «сюзерен-вассал», а не на сюзерена целиком.
        """
        return f"{self.turn}:{actor_id}:{action}"

    def _ledger_exhausted(self, actor_id: str, action: str, limit: int) -> bool:
        """Исчерпан ли лимит ``limit`` раз за ход для ``actor_id``."""
        key = self._ledger_key(actor_id, action)
        return self.action_ledger.get(key, 0) >= max(1, int(limit))

    def _ledger_spend(self, actor_id: str, action: str) -> None:
        """Израсходовать одну единицу лимита. Вызывается только при успехе."""
        key = self._ledger_key(actor_id, action)
        self.action_ledger[key] = self.action_ledger.get(key, 0) + 1

    # ---------------- права и казна ----------------

    def realm_owning(self, province_idx: int) -> Optional[str]:
        """Королевство, которое ФАКТИЧЕСКИ владеет провинцией (по ``owner``).

        Нейтральная провинция возвращает ``None``: платить за неё некому.
        Если бы на карте появились два королевства одной нации, выбор детерминирован
        (по отсортированному id) — иначе две машины разошлись бы по хешу.
        """
        if not isinstance(province_idx, int) or isinstance(province_idx, bool):
            return None
        if not 0 <= province_idx < len(self.provinces):
            return None
        nation = getattr(self.province(province_idx), "owner", "neutral")
        for realm_id in sorted(self.realms):
            if self.realms[realm_id].nation == nation:
                return realm_id
        return None

    def _command_ruler(self, realm_id: Optional[str],
                       actor_id: Optional[str] = None) -> Optional[Character]:
        """Живой правитель королевства — и только он вправе тратить его казну.

        ``actor_id`` необязателен: команда провинции и так знает, чья это
        земля, и по умолчанию действует от лица правителя. Явный ЧУЖОЙ
        ``actor_id`` — отказ: полномочия проверяются, а не угадываются.
        """
        realm = self.realms.get(realm_id) if isinstance(realm_id, str) else None
        if realm is None:
            return None
        if actor_id is not None and actor_id != realm.ruler_id:
            return None
        ruler = self.characters.get(realm.ruler_id or "")
        if ruler is None or not ruler.alive:
            return None
        return ruler

    def _realm_of_ruler(self, actor: Character) -> Optional[Realm]:
        """Королевство под управлением персонажа (у короля), иначе ``None``."""
        if actor.rank is not TitleRank.KING:
            return None
        return self.realms.get(actor.realm_id or "")

    def purse_of(self, actor: Character) -> int:
        """Сколько золота может тратить персонаж: казна realm'а или свой кошель.

        Король распоряжается казной королевства (её и наполняет ``tick_realms``),
        а герцог, у которого своего realm'а нет, — личным кошель. Оба числа
        живут в снапшоте, поэтому подарок одинаково воспроизводится после
        round-trip.
        """
        realm = self._realm_of_ruler(actor)
        return realm.gold if realm is not None else actor.gold

    def _charge_purse(self, actor: Character, amount: int) -> bool:
        """Списать ``amount`` золота у персонажа. False — не хватило, ничего не списано."""
        if amount <= 0:
            return True
        realm = self._realm_of_ruler(actor)
        if realm is not None:
            if realm.gold < amount:
                return False
            realm.gold -= amount
            return True
        if actor.gold < amount:
            return False
        actor.gold -= amount
        return True

    # ---------------- индексы и доступ ----------------

    def _rebuild_province_index(self):
        self._province_duchy.clear()
        for d in self.duchies.values():
            for idx in d.de_jure_provinces:
                self._province_duchy[idx] = d.id

    def province(self, idx: int):
        return self.provinces[idx]

    def duchy_of(self, province_idx: int) -> Optional[str]:
        """De jure герцогство провинции."""
        return self._province_duchy.get(province_idx)

    def counties_of_duchy(self, duchy_id: str) -> List[int]:
        d = self.duchies.get(duchy_id)
        return list(d.de_jure_provinces) if d else []

    def provinces_of_realm(self, realm_id: str) -> List[int]:
        """Фактические владения королевства — по владельцу провинции."""
        nation = self.realms[realm_id].nation
        return [i for i, p in enumerate(self.provinces) if getattr(p, "owner", "neutral") == nation]

    def holder_of_duchy(self, duchy_id: str) -> Optional[Character]:
        """De jure держатель герцогства.

        ВАЖНО: это НЕ «кто владеет герцогством на самом деле». Ответ на
        последний вопрос — ``de_facto_holder_of_duchy``, и эти два персонажа
        могут быть разными людьми разных наций: соседний король может
        захватить все пять графств Ravenhold, и duke_aldric при этом останется
        de jure герцогом (от него зависит ``liege_of`` его баронов).
        """
        d = self.duchies.get(duchy_id)
        if d and d.holder_id:
            return self.characters.get(d.holder_id)
        return None

    # ---------------- de jure / de facto ----------------

    def nation_of(self, province_idx: int) -> str:
        """Нация, ФАКТИЧЕСКИ владеющая провинцией (``province.owner``)."""
        if not isinstance(province_idx, int) or isinstance(province_idx, bool):
            return "neutral"
        if not 0 <= province_idx < len(self.provinces):
            return "neutral"
        return str(getattr(self.province(province_idx), "owner", "neutral"))

    def counties_factually_held(self, duchy_id: str, nation: str) -> List[int]:
        """De jure провинции герцогства, которые фактически принадлежат нации.

        Порядок — ``de jure`` (как в ``Duchy.de_jure_provinces``), чтобы и
        доход, и левейс, и любая проверка «сумма по этому списку» совпадали.
        Пустая нация не совпадёт ни с одной провинцией, поэтому нейтральные
        графства не достаются никому.
        """
        return [idx for idx in self.counties_of_duchy(duchy_id)
                if self.nation_of(idx) == nation]

    def majority_nation_of_duchy(self, duchy_id: str) -> Optional[str]:
        """Нация, владеющая строгим большинством de jure провинций герцогства.

        Правило и его обоснование — в разделе констант этапа 2. Кратко: строгое
        ``больше половины``, иначе ``None`` (ничья 3:2 тоже ничья). Подсчёт идёт
        по отсортированным нациям, поэтому ответ одинаков на любой машине.

        ``neutral`` в подсчёте НЕ участвует: это не страна, а «никто». Иначе
        полностью нейтральное герцогство объявило бы большинством ``neutral``,
        а знаменатель («больше половины от de jure провинций») остался бы тем
        же — то есть пустое герцогство получило бы несуществующего правителя.
        При этом в знаменатель ``neutral`` ВХОДИТ: половина нейтральных земель не
        делает оставшуюся половину большинством.
        """
        provinces = self.counties_of_duchy(duchy_id)
        if not provinces:
            return None
        tally: Dict[str, int] = {}
        for idx in provinces:
            nation = self.nation_of(idx)
            if nation == NEUTRAL_NATION:
                continue
            tally[nation] = tally.get(nation, 0) + 1
        best_nation: Optional[str] = None
        best_count = 0
        for nation in sorted(tally):
            count = tally[nation]
            if count > best_count:
                best_nation, best_count = nation, count
        if best_nation is None or best_count * 2 <= len(provinces):
            return None
        return best_nation

    def recompute_de_facto_holder(self, duchy_id: str) -> Optional[str]:
        """Пересчитать ``de_facto_holder_id`` и вернуть его (или ``None``).

        Кто именно становится de-факто держателем при известном большинстве:

        1. de jure держатель, если он жив и его нация и есть большинство —
           это обычный случай, и тогда de jure и de facto совпадают;
        2. иначе король большинствующей нации — потому что страна, владеющая
           областью без всякого титула, правит ею королём, и именно его
           казна получает ``realm_income`` с этих графств;
        3. иначе ``None``: большинство есть, а правителя у нации нет —
           платить некому.

        Персонаж возвращается живым: ``de_facto_holder_of_duchy`` не отдаёт
        трупы в UI (см. там же).
        """
        duchy = self.duchies.get(duchy_id)
        if duchy is None:
            return None
        nation = self.majority_nation_of_duchy(duchy_id)
        if nation is None:
            duchy.de_facto_holder_id = None
            return None
        holder = self.holder_of_duchy(duchy_id)
        if holder is not None and holder.alive and holder.nation == nation:
            duchy.de_facto_holder_id = holder.id
            return holder.id
        for realm_id in sorted(self.realms):
            realm = self.realms[realm_id]
            if realm.nation != nation or not realm.ruler_id:
                continue
            king = self.characters.get(realm.ruler_id)
            if king is not None and king.alive:
                duchy.de_facto_holder_id = king.id
                return king.id
        duchy.de_facto_holder_id = None
        return None

    def recompute_de_facto_holders(self) -> List[str]:
        """Пересчитать de-факто держателя у ВСЕХ герцогств (по sorted id).

        Единственный честный способ привести иерархию в согласие с картой,
        когда ``province.owner`` меняли мимо ``transfer_county`` (например,
        пока ``world_map.py`` и ``war.py`` не переведены на неё). Дёшево:
        десять герцогств и пятьдесят провинций.
        """
        for duchy_id in sorted(self.duchies):
            self.recompute_de_facto_holder(duchy_id)
        return []

    def de_facto_holder_of_duchy(self, duchy_id: str) -> Optional[Character]:
        """Персонаж, который правит герцогством ПО ФАКТУ (``None`` — ничья).

        Читает вычисленное поле, а не пересчитывает на лету: иначе результат
        зависел бы от того, кто последним писал в ``province.owner``, и поле в
        снапшоте перестало бы быть правдой. Пересчёт живёт в
        ``recompute_de_facto_holder`` и вызывается из ``transfer_county``.

        Мёртвый держатель не возвращается: панель герцогства не должна
        показывать труп правителем (см. ``settle_deaths``).
        """
        duchy = self.duchies.get(duchy_id)
        if duchy is None or not duchy.de_facto_holder_id:
            return None
        holder = self.characters.get(duchy.de_facto_holder_id)
        if holder is None or not holder.alive:
            return None
        return holder

    def holder_of_county(self, province_idx: int) -> Optional[Character]:
        """Кто держит графство ПО ФАКТУ — по ``Character.province_idx``.

        Поиск идёт по отсортированным id: в мире должен быть ровно один
        такой персонаж на графство, но если поломалось что-то ещё, ответ
        обязан быть одинаковым на всех машинах.
        """
        if not isinstance(province_idx, int) or isinstance(province_idx, bool):
            return None
        for ch in sorted(self.characters.values(), key=lambda c: c.id):
            if ch.province_idx == province_idx:
                return ch
        return None

    # ---------------- единая точка передачи владения (этап 2) ----------------

    def transfer_county(self, province_idx: int, new_nation: object,
                        new_holder_id: Optional[object] = None, *,
                        cause: str = "") -> List[str]:
        """Передать графство: сменить нацию-владельца и (необязательно) держателя.

        Единственное место в модуле, где меняется ``province.owner`` или
        ``Character.province_idx``. Пока это правило соблюдается не везде
        (``world_map.py`` и ``war.py`` пишут ``province.owner`` напрямую —
        список мест приложен к этапу), иерархия остаётся согласованной.

        Что обязано произойти (все инварианты проверяются тестами):

        * ``province.owner`` становится ``new_nation``;
        * прежний держатель теряет ``province_idx`` и становится безземельным
          (``landless_turns = 0``, дальше ``tick_vassals`` начнёт снимать
          мнение по ``LANDLESS_OPINION_DECAY``);
        * новый держатель получает ``province_idx``, а его ``duchy_id``
          пересчитывается по de jure — ЕСЛИ он не держит герцогства (иначе
          подарок графства герцогу тихо отнял бы у него дукцию, а с ней всех
          его баронов; см. ``_grant_fief_now``);
        * ``contracts[id].liege_id`` пересчитывается у обоих затронутых
          персонажей, потому что «вассал по контракту» и «вассал по
          ``liege_of``» обязаны быть одним и тем же человеком;
        * ``Duchy.de_facto_holder_id`` пересчитывается у прежнего и нового
          герцогства — того, где лежала провинция, и того, где оказался новый
          держатель, если он сменил дукцию;
        * ``cause`` попадает в текст события, чтобы журнал сервера объяснял,
        откуда взялась передача (выдача фьефа, отзыв, захват на карте).

        Прежний держатель НЕ теряет ``duchy_id``: он остаётся в своём
        герцогстве (он ведь мог быть герцогом, а теперь просто без графства).
        Ранг тоже не трогается — этим занимается ``refresh_rank``.

        Мусор на входе (не число, выход за границы, пустая нация, неизвестный
        держатель) даёт пустой список: клиенту нечего показывать, а состояние
        обязано остаться прежним.
        """
        if not isinstance(province_idx, int) or isinstance(province_idx, bool) \
                or not 0 <= province_idx < len(self.provinces):
            return []
        if not isinstance(new_nation, str) or not new_nation:
            return []
        place = getattr(self.province(province_idx), "name", f"#{province_idx}")
        reason = f" ({cause})" if cause else ""
        old_duchy = self.duchy_of(province_idx)
        old_holder = self.holder_of_county(province_idx)
        new_holder: Optional[Character] = None
        if new_holder_id is not None:
            new_holder = self.characters.get(new_holder_id) \
                if isinstance(new_holder_id, str) else None
            if new_holder is None:
                return []

        events: List[str] = []
        old_nation = self.nation_of(province_idx)
        self.province(province_idx).owner = new_nation

        touched = set()
        if old_holder is not None and (new_holder is None
                                       or old_holder.id != new_holder.id):
            events.append(f"{old_holder.name} теряет {place}{reason}")
            old_holder.province_idx = None
            old_holder.landless_turns = 0
            self.refresh_rank(old_holder.id)
            touched.add(old_holder.id)

        if new_holder is not None:
            events.append(f"{place}: {new_holder.name}{reason}")
            new_holder.province_idx = province_idx
            new_holder.landless_turns = 0
            holds_duchy = new_holder.rank is TitleRank.DUKE \
                and new_holder.duchy_id is not None
            if old_duchy is not None and not holds_duchy:
                new_holder.duchy_id = old_duchy
            touched.add(new_holder.id)
            self.refresh_rank(new_holder.id)

        # контракт должен совпадать с фактическим сюзереном: иначе «мой вассал
        # по контракту» и «мой вассал по liege_of» — разные люди
        for character_id in sorted(touched):
            self._sync_contract(self.characters.get(character_id))

        # de-факто владелец меняется у прежнего герцогства и у нового
        for duchy_id in sorted({d for d in (old_duchy, new_holder.duchy_id
                                            if new_holder is not None else None)
                                if d}):
            self.recompute_de_facto_holder(duchy_id)

        if old_nation != new_nation:
            events.append(f"{place}: владелец {old_nation} → {new_nation}")
        return events

    def _sync_contract(self, ch: Optional[Character], *, create: bool = True) -> None:
        """Привести ``contracts[ch.id]`` в соответствие с ``liege_of(ch)``.

        Контракт без сюзерена бессмыслен и опасен: по нему платят налоги и
        копится тирания. Поэтому если сюзерена нет — контракт удаляется (ровно
        так же у королей: ``test_nobody_may_command_a_king`` требует, чтобы у
        короля контракта не было), а если есть — уровень сохраняется, а меняется
        только ``liege_id``.

        ``create=False`` — режим «не заводить новых контрактов»: обновить
        существующие и убрать осиротевшие. Он нужен ``settle_deaths``, который
        пересчитывает контракты ВСЕХ затронутых сменой титула: если бы он заводил
        контракт там, где его не было, то набор контрактов зависел бы от того,
        кто и когда умер, а это не состояние, а случайность. ``transfer_county``
        создаёт контракт: там смена сюзерена — прямое следствие выдачи земли.
        """
        if ch is None or not isinstance(ch.id, str):
            return
        liege = self.liege_of(ch.id)
        if liege is None or not liege.alive:
            self.contracts.pop(ch.id, None)
            return
        old = self.contracts.get(ch.id)
        if old is None and not create:
            return
        level = old.level if old is not None else int(ch.contract_level)
        self.contracts[ch.id] = VassalContract(
            liege_id=liege.id, vassal_id=ch.id, level=level)

    # ---------------- ранг как состояние (этап 4.1) ----------------

    def promote(self, character_id: str, rank: object) -> List[str]:
        """Явно выдать персонажу ранг ``rank`` (событие только при смене).

        Обёртка над прямым присваиванием ``Character.rank``: ранг — состояние,
        поэтому любая его смена обязана быть видна в журнале, а не «молча
        исправиться» где-то в тике. Неизвестное значение и не-персонаж дают
        пустой список.
        """
        if not isinstance(character_id, str):
            return []
        ch = self.characters.get(character_id)
        if ch is None or not isinstance(rank, TitleRank):
            return []
        if ch.rank is rank:
            return []
        old = ch.rank
        ch.rank = rank
        return [f"{ch.name}: ранг {old.value} → {rank.value}"]

    def expected_rank(self, character_id: str) -> TitleRank:
        """Какой ранг персонаж должен иметь, если судить по его титулам.

        Правило ровно одно и оно историческое: правитель королевства — король,
        держатель герцогства — герцог, все прочие, включая безземельных —
        бароны. Мёртвым ранг НЕ назначается: у трупа нет титулов, но и
        переписывать его ранг незачем — он всё равно выпадает из ``tick_vassals``
        по ``alive``, а держать в снапшоте осмысленное «был герцог» полезнее,
        чем «герцог, который правит».
        """
        ch = self.characters.get(character_id) if isinstance(character_id, str) else None
        if ch is None or not ch.alive:
            return ch.rank if ch is not None else TitleRank.BARON
        for realm_id in sorted(self.realms):
            if self.realms[realm_id].ruler_id == ch.id:
                return TitleRank.KING
        for duchy_id in sorted(self.duchies):
            if self.duchies[duchy_id].holder_id == ch.id:
                return TitleRank.DUKE
        return TitleRank.BARON

    def refresh_rank(self, character_id: str) -> List[str]:
        """Свести ранг персонажа с его титулами (``expected_rank``).

        Вызывается после любой смены титула: выдача и отзыв земли, смерть
        правителя, наследование. Именно это чинит главный баг этапа 4: раньше
        ранг был константой, и герцог, получивший герцогство из рук умершего
        duke, оставался бароном — а барон без сюзерена целиком выпадал из
        ``tick_vassals``, то есть мнение, лояльность и мятеж замирали.
        """
        ch = self.characters.get(character_id) if isinstance(character_id, str) else None
        if ch is None:
            return []
        return self.promote(character_id, self.expected_rank(character_id))

    def liege_of(self, character_id: str) -> Optional[Character]:
        """Сюзерен персонажа: король для герцога, герцог для барона."""
        ch = self.characters.get(character_id)
        if ch is None:
            return None
        if ch.rank is TitleRank.KING:
            return None
        if ch.rank is TitleRank.DUKE:
            realm = self.realms.get(ch.realm_id or "")
            return self.characters.get(realm.ruler_id) if realm else None
        if ch.duchy_id:
            holder = self.holder_of_duchy(ch.duchy_id)
            if holder and holder.id != ch.id:
                return holder
        return None

    def vassals_of(self, character_id: str) -> List[Character]:
        liege = self.characters.get(character_id)
        out: List[Character] = []
        for ch in self.characters.values():
            if ch.id == character_id or not ch.alive:
                continue
            if self.liege_of(ch.id) and self.liege_of(ch.id).id == character_id:
                out.append(ch)
        out.sort(key=lambda c: c.id)
        return out

    def powerful_vassals(self, realm_id: str, county_threshold: int = 2,
                         duchy_threshold: int = 1, kingdom_threshold: int = 5
                         ) -> List[Character]:
        """Сильные вассалы по размеру (по аналогии с CK3).

        Считаются только герцоги: король — не вассал самому себе. Порог
        по умолчанию снижен до двух графств, потому что на текущей карте
        в герцогстве всего два барона (масштаб CK3 — десятки графств).
        ``kingdom_threshold`` оставлен для будущих сценариев, где могущество
        считается по числу герцогств.
        """
        out: List[Character] = []
        for ch in self.characters.values():
            if not ch.alive or ch.realm_id != realm_id:
                continue
            if ch.rank is TitleRank.DUKE and self._baron_count(ch) >= county_threshold:
                out.append(ch)
        out.sort(key=lambda c: (-self.vassal_power(c), c.id))
        return out

    def _baron_count(self, ch: Character) -> int:
        """Сколько графств держит герцог/король (для герцога — его бароны)."""
        if ch.rank is TitleRank.KING:
            return len(self.provinces_of_realm(ch.realm_id or ""))
        if ch.rank is TitleRank.DUKE and ch.duchy_id:
            holder = self.holder_of_duchy(ch.duchy_id)
            if holder and holder.id != ch.id:
                return 0
            return sum(1 for b in self.characters.values()
                       if b.rank is TitleRank.BARON and b.duchy_id == ch.duchy_id and b.alive)
        return 1

    def vassal_power(self, ch: Character) -> int:
        """«Сеньоритет» — сводная сила персонажа. Единственное число в UI короля."""
        if not ch.alive:
            return 0
        return self._baron_count(ch) * 10 + ch.influence + ch.martial * 2 + ch.troops_hint()

    def liege_authority(self, character_id: str) -> int:
        """Королевская власть (0..3) над персонажем. Ниже — слабее контроль.

        Поднимается по всей цепочке сюзеренов до корня: авторитет короля
        распространяется и на герцога, и на его баронов.
        """
        ch = self.characters.get(character_id)
        if ch is None:
            return 0
        node: Optional[Character] = ch
        seen = set()
        while node is not None and node.id not in seen:
            seen.add(node.id)
            if node.rank is TitleRank.KING:
                realm = self.realms.get(node.realm_id or "")
                if realm is None:
                    return 0
                return max(0, min(3, int(realm.crown_authority)))
            node = self.liege_of(node.id)
        return 0

    # ---------------- экономика графства ----------------

    def county_income(self, province_idx: int) -> int:
        """Доход графства за ход: 35% hearths с множителями."""
        p = self.province(province_idx)
        hearths = getattr(p, "hearths", 0)
        if hearths <= 0:
            return 0
        mult = (prosperity_tax_multiplier(getattr(p, "prosperity", 0))
                * loyalty_tax_multiplier(getattr(p, "loyalty", 70))
                * security_tax_multiplier(getattr(p, "security", 10))
                * development_tax_multiplier(getattr(p, "development", 1)))
        return int(hearths * 35 // 100 * mult)

    def county_levy(self, province_idx: int) -> int:
        p = self.province(province_idx)
        dev = getattr(p, "development", 1)
        base = getattr(p, "hearths", 0) // 2
        return max(0, int(base * development_tax_multiplier(dev)))

    def garrison_cap(self, province_idx: int) -> int:
        """Потолок гарнизона: ``(fort_level + 1) * GARRISON_CAP_PER_FORT``.

        Даёт ``fort_level`` смысл: деревня держит сотню, город — две,
        крепость-столица — три. Без стен гарнизон всё равно держать
        можно, но дороже и меньше.

        ВАЖНО: потолок НЕ применяется автоматически в тиках. Причина
        чистая: существующие тесты (``test_loyalty_rises_with_garrison``)
        ставят гарнизон в деревню и ждут от него роста лояльности — то
        есть «нелегальный» гарнизон должен продолжать работать. Сжимать
        гарнизон до потолка будет команда найма (этап 3), где игрок
        задаёт число солдат явно; до тех пор порог только спрашивается,
        но не принуждает.
        """
        fort = max(0, int(getattr(self.province(province_idx), "fort_level", 0)))
        return (fort + 1) * GARRISON_CAP_PER_FORT

    def garrison_upkeep(self, realm_id: str) -> int:
        """Содержание гарнизонов королевства за ход, в золоте.

        Считается **только по провинциям ЭТОГО realm'а** — гарнизоны
        нейтральных и чужих земель никто не кормит. Первые
        ``GARRISON_IS_FREE_THRESHOLD`` солдат на провинцию бесплатны
        (сейчас это ноль, то есть платный весь гарнизон).
        """
        total = 0
        for idx in self.provinces_of_realm(realm_id):
            billable = max(0, int(getattr(self.province(idx), "garrison", 0))
                           - GARRISON_IS_FREE_THRESHOLD)
            # пропорционально, а не «по сотням»: иначе гарнизон в 99 солдат
            # бесплатен, а разорённое королевство стягивает войска до 99
            # и больше не платит ничего (обход содержания)
            total += billable * GARRISON_UPKEEP_PER_100 // 100
        return total

    def duchy_income(self, duchy_id: str) -> int:
        """Доход герцогства за ход — ТОЛЬКО по фактически принадлежащим графствам.

        Именно здесь закрывался двойной доход: до этапа 2 сумма бралась по
        ВСЕМ de jure провинциям герцогства, не глядя на ``owner``. Завоёванное
        иностранное графство платило и завоевателю (``realm_income`` — по факту),
        и прежнему герцогу (здесь — по титулу), то есть одна деревня
        засчитывалась в казну дважды.

        Теперь платит нация de-факто держателя (``de_facto_holder_of_duchy``),
        и только те de jure провинции, которые реально её (``factually_held``).
        Если большинства нет или у большинствующей нации нет живого правителя —
        ноль: платить некому, и это честнее, чем платить пустым герцогством.
        """
        holder = self.de_facto_holder_of_duchy(duchy_id)
        if holder is None:
            return 0
        return sum(self.county_income(i)
                   for i in self.counties_factually_held(duchy_id, holder.nation))

    def duchy_levy(self, duchy_id: str) -> int:
        """Левейс герцогства — по тому же правилу, что и ``duchy_income``."""
        holder = self.de_facto_holder_of_duchy(duchy_id)
        if holder is None:
            return 0
        return sum(self.county_levy(i)
                   for i in self.counties_factually_held(duchy_id, holder.nation))

    def realm_income(self, realm_id: str) -> int:
        """Фактический доход королевства: то, что платят его владения."""
        nation = self.realms[realm_id].nation
        total = 0
        for idx, p in enumerate(self.provinces):
            if getattr(p, "owner", "neutral") != nation:
                continue
            total += self.county_income(idx)
        return total

    def realm_levy(self, realm_id: str) -> int:
        nation = self.realms[realm_id].nation
        return sum(self.county_levy(i) for i, p in enumerate(self.provinces)
                   if getattr(p, "owner", "neutral") == nation)

    # ---------------- права по рангу (этап 1.1) ----------------
    #
    # До этого этапа «кто вправе выдать землю» знал только UI. Для сети это дыра:
    # король мог переписать контракт ЧУЖОГО вассала, потому что ``set_contract``
    # сам подставлял ``liege_of(vassal_id)`` и ни о чём не спрашивал. Теперь
    # правило живёт здесь, в состоянии, и проверяется по ``by_actor``.
    #
    # Общий вид проверки — две ступени:
    #
    # * актор существует и ЖИВОЙ (``_actor_of``);
    # * актор — сюзерен цели нужного ранга (``_command_refusal``): бароном
    #   командует его непосредственный сюзерен (держатель герцогства, то есть
    #   герцог), герцогом — только король его realm'а, королем — никто.

    def _actor_of(self, actor_id: object) -> Optional[Character]:
        """Персонаж-исполнитель команды: существующий и ЖИВОЙ, иначе ``None``.

        Отдельный метод, потому что «существует» и «жив» — это разные проверки,
        а сливать их в одну строку в трёх местах означает забыть про смерть
        где-нибудь в одном из них.
        """
        if not isinstance(actor_id, str):
            return None
        actor = self.characters.get(actor_id)
        if actor is None or not actor.alive:
            return None
        return actor

    def _command_refusal(self, actor: Optional[Character],
                         target: Character) -> Optional[str]:
        """Почему ``actor`` НЕ вправе командовать ``target`` (``None`` — вправе).

        ``actor is None`` означает «не персонаж этой иерархии или мёртв»;
        проверка цели тоже здесь, потому что приказ мёртвому бессмысленен так же,
        как приказ от мёртвого. Сообщение всегда ОДНО и читаемое: это то, что
        UI показывает игроку вместо тихого ничего.
        """
        if actor is None:
            return "актор не персонаж этой иерархии или уже мёртв"
        if not target.alive:
            return f"{target.name}: мёртвым приказы не отдают"
        required = COMMAND_MIN_RANK.get(target.rank)
        if required is None:
            return f"{target.name}: королю не подчиняется никто"
        if actor.tier < required:
            return f"{actor.name}: не сюзерен {target.name}"
        liege = self.liege_of(target.id)
        if liege is None or liege.id != actor.id:
            return f"{actor.name}: не сюзерен {target.name}"
        return None

    def _realm_of_actor(self, actor: Character) -> Optional[Realm]:
        """Королевство, землями которого распоряжается персонаж.

        У короля оно своё (``Realm.ruler_id``), у герцога — realm его нации:
        ``Realm`` у герцога нет, но земля, которую он вправе раздавать, от
        ``province.owner``, то есть от нации. Выбор детерминирован (по
        отсортированному id) — на случай двух королевств одной нации.
        """
        realm = self._realm_of_ruler(actor)
        if realm is not None:
            return realm
        for realm_id in sorted(self.realms):
            if self.realms[realm_id].nation == actor.nation:
                return self.realms[realm_id]
        return None

    # ---------------- контракты и мнение ----------------

    def contract_of(self, vassal_id: str) -> Optional[VassalContract]:
        return self.contracts.get(vassal_id)

    def set_contract(self, vassal_id: str, level: int, *,
                     by_actor: Optional[str] = None) -> List[str]:
        """Смена уровня контракта. Повышение копит тиранию и режет мнение.

        ``by_actor`` (этап 1.1) — проверка прав, обязательная для сети:

        * ``None`` — прежнее поведение: значение клампится в
          ``0..len(CONTRACT_LEVELS) - 1``, никаких прав не спрашивается
          (этим путём зовёт UI-обёртка и старые тесты);
        * актор обязан быть живым сюзереном вассала нужного ранга (см.
          ``_command_refusal``): герцогом командует король его realm'а, бароном
          — непосредственный сюзерен;
        * значение вне диапазона ОТКЛОНЯЕТСЯ, а не клампится: клиент посчитал
          бы по своей шкале и показал игроку не тот контракт, который получит
          сервер. Молчаливая подгонка здесь стоила бы дороже, чем отказ;
        * действует тот же ``action_ledger``, что у остальных команд:
          ``CONTRACT_CHANGES_PER_TURN`` раз за ход на актора, и лимит
          проверяется ПОСЛЕДНИМ, чтобы отказ по существу не съел право.
        """
        ch = self.characters.get(vassal_id)
        if ch is None:
            return []
        actor: Optional[Character] = None
        if by_actor is not None:
            actor = self._actor_of(by_actor)
            refusal = self._command_refusal(actor, ch)
            if refusal is None:
                value = as_int(level)
                if value is None:
                    refusal = "уровень контракта должен быть числом"
                elif not 0 <= value <= len(CONTRACT_LEVELS) - 1:
                    refusal = (f"уровень контракта {value} вне диапазона "
                               f"0..{len(CONTRACT_LEVELS) - 1}")
                else:
                    level = value
            if refusal is not None:
                return [f"{ch.name}: {refusal}"]
            if self._ledger_exhausted(actor.id, ACTION_SET_CONTRACT,
                                      CONTRACT_CHANGES_PER_TURN):
                return [f"{actor.name}: контракт этому вассалу уже меняли в этом ходу"]
            self._ledger_spend(actor.id, ACTION_SET_CONTRACT)
        return self._set_contract_now(vassal_id, level)

    def _set_contract_now(self, vassal_id: str, level: int) -> List[str]:
        """Ядро смены контракта без проверки прав: клампит и применяет.

        Отделено от ``set_contract``, потому что ``_apply_order`` исполняет
        УЖЕ ПРИНЯТЫЙ приказ и не должен повторно спрашивать права (которые к
        моменту исполнения всё равно проверяются заново, но по-другому —
        через ``by_actor``).
        """
        level = max(0, min(len(CONTRACT_LEVELS) - 1, int(level)))
        ch = self.characters.get(vassal_id)
        if ch is None:
            return []
        old = self.contracts.get(vassal_id)
        old_level = old.level if old is not None else level
        if old is not None and old_level == level:
            return [f"{ch.name}: контракт уже {CONTRACT_LEVELS[level]['name']}"]
        liege = self.liege_of(vassal_id)
        self.contracts[vassal_id] = VassalContract(
            liege_id=liege.id if liege else "",
            vassal_id=vassal_id, level=level)
        events: List[str] = []
        if old is None or level > old_level:
            delta = -10 if (old and level > old_level) else -5
            ch.opinion_of_liege = max(-100, ch.opinion_of_liege + delta)
            events.append(f"{ch.name}: контракт повышен, мнение {ch.opinion_of_liege}")
        else:
            ch.opinion_of_liege = min(100, ch.opinion_of_liege + 5)
            events.append(f"{ch.name}: контракт ослаблен, мнение {ch.opinion_of_liege}")
        return events

    def can_accept_order(self, vassal_id: str, order: object) -> bool:
        """Может ли вассал принять приказ сюзерена (CK3-порог).

        Аргумент ``order`` наконец-то значим. Он примает ``Order``,
        ``OrderKind`` или строку, а вес приказа задаёт, насколько глубокая
        ненависть ещё прощается: ``GIFT`` (вес 1) — до ``-10`` мнения,
        ``RAISE_LEVY`` (вес 5) — только до ``-30``. Поэтому от мелкой просьбы
        можно отказаться «почти без последствий», а от тяжёлой — почти нельзя.

        Неизвестная строка (старый UI вида ``"raise_the_siege"``) весит как
        ``ORDER_DEFAULT_WEIGHT``, поэтому прежние вызовы ведут себя как раньше:
        при ``opinion_of_liege == 0`` приказ принимается.

        Второй путь — абсолютная королевская власть: при ``crown_authority == 3``
        вассал соглашается даже при ``-50`` мнения, но не при ``-60`` и ниже.
        """
        ch = self.characters.get(vassal_id) if isinstance(vassal_id, str) else None
        if ch is None or not ch.alive:
            return False
        if ch.opinion_of_liege >= order_refusal_threshold(order):
            return True
        # при глубокой ненависти выручает только абсолютная королевская власть
        return self.liege_authority(vassal_id) >= 3 and ch.opinion_of_liege > -60

    def grant_fief(self, province_idx: int, baron_id: str, *,
                   by_actor: Optional[str] = None) -> List[str]:
        """Передать графство барону. Главный способ снизить мятеж.

        ``duchy_id`` пересчитывается всегда: иначе барон, получивший землю
        в чужом герцогстве, остался бы вассалом прежнего сюзерена.

        ``by_actor`` (этап 1.1) — проверка прав, обязательная для сети:

        * ``None`` — прежнее поведение без проверок (его зовут UI-обёртка и
          308 старых тестов, поэтому путь обязан остаться прежним);
        * актор обязан быть живым и быть сюзереном барона по рангу: бароном
          командует его непосредственный сюзерен (герцог), герцогом — король
          его realm'а;
        * провинция должна ФАКТИЧЕСКИ принадлежать realm'у актора
          (``province.owner == realm.nation``). Именно эта проверка закрывает
          дыру «выдать нейтральную землю»: realm'у, который её не платит
          налога, она и не нужна;
        * получатель не должен уже держать графство. Правило обмена сознательно
          ЖЁСТКОЕ (обмен только через явный отзыв), потому что тихая подмена
          земли внутри команды «выдать» означала бы отзыв без его последствий
          (−20 мнения и −20 лояльности) — то есть спрятала бы разрушительное
          решение в формулировке, которая звучит безобидно. Разрушительное
          должно быть явным: ``revoke_fief`` с отзывом, потом ``grant_fief``
          с новой землёй.

        ``province.owner`` меняется на нацию получателя. Раньше он НЕ менялся
        вовсе, и это было ошибкой, а не «особенностью модели»: после этапа 2
        ``duchy_income`` считает только графства, фактически принадлежащие
        нации de-факто держателя, поэтому выданное чужое или нейтральное графство
        не платило бы НИКОМУ — ни прежнему хозяину земли (он её уже не держит),
        ни новому сюзерену (``realm_income`` идёт по ``owner``). То есть
        «выданная земля» была бы владением без дохода и без видимости.

        Для ВНУТРЕННЕЙ выдачи (``by_actor``) смена ``owner`` — операция вхолостую:
        провинция обязана принадлежать realm'у актора, а получатель — его
        вассал той же нации, поэтому владелец не меняется. Меняется он только
        на неконтролируемом пути ``by_actor=None``, где «выдать можно что угодно
        кому угодно» — и там смена ``owner`` как раз и означает честную аннексию.
        """
        ch = self.characters.get(baron_id)
        if ch is None:
            return []
        if by_actor is not None:
            refusal = self._grant_fief_refusal(by_actor, ch, province_idx)
            if refusal is not None:
                return [refusal]
        return self._grant_fief_now(province_idx, ch)

    def _grant_fief_now(self, province_idx: int, ch: Character) -> List[str]:
        """Ядро выдачи земли без проверки прав (см. ``_set_contract_now``).

        Всю работу делает ``transfer_county`` — единая точка передачи владения.
        Здесь остаётся только то, что относится к выдаче, а не к передаче:
        бонус «получил землю» и текст события.

        Бонус даётся по факту отсутствия графства (``province_idx is None``), а
        не по ``is_ruler``: герцог и без графства правитель, но король вправе
        пожаловать ему графство первым, и такой дар должен быть замечен вассалом
        так же, как земля для безземельного барона.

        Повторная выдача того же самого графства — операция вхолостую и молчащая
        (``[]``): состояние не меняется, а «событие» без изменения только
        засоряет журнал.
        """
        if ch.province_idx == province_idx:
            return []
        was_landless = ch.province_idx is None
        events = self.transfer_county(province_idx, ch.nation, ch.id,
                                      cause="выдан фьеф")
        ch.landless_turns = 0
        if was_landless:
            ch.opinion_of_liege = min(100, ch.opinion_of_liege + 20)
            ch.loyalty = min(100, ch.loyalty + 10)
            events.append(f"{ch.name} получил землю, мнение {ch.opinion_of_liege}")
        return events

    def _grant_fief_refusal(self, actor_id: object, ch: Character,
                            province_idx: object) -> Optional[str]:
        """Почему ``actor_id`` не вправе отдать ``province_idx`` барону ``ch``.

        Только для пути с ``by_actor`` и для ``issue_order``: они оба обязаны
        отказать ДО выдачи, а не «выдать и посмотреть, что получилось».
        """
        actor = self._actor_of(actor_id)
        refusal = self._command_refusal(actor, ch)
        if refusal is not None:
            return refusal
        if not isinstance(province_idx, int) or isinstance(province_idx, bool) \
                or not 0 <= province_idx < len(self.provinces):
            return f"{ch.name}: графство задаётся номером провинции, а не «{province_idx}»"
        realm = self._realm_of_actor(actor)
        if realm is None:
            return f"{actor.name}: у него нет королевства, чтобы раздавать землю"
        place = getattr(self.province(province_idx), "name", f"#{province_idx}")
        if getattr(self.province(province_idx), "owner", "neutral") != realm.nation:
            return f"{realm.name}: {place} не под его властью"
        if ch.province_idx is not None and ch.province_idx != province_idx:
            return (f"{ch.name} уже держит графство #{ch.province_idx}: "
                    f"обмен землями только через отзыв")
        return None

    def revoke_fief(self, baron_id: str, *,
                    by_actor: Optional[str] = None) -> List[str]:
        """Отозвать графство: земля возвращается королевству, мнение падает.

        Земля возвращается В ПУЛ realm'а, а не просто исчезает: прежний код
        обнулял ``province_idx`` и больше ничего не делал, из-за чего отозванное
        графство выглядело как ничейная земля — оно продолжало платить налоги
        державшей нации (это правильно), но не было видно нигде. Теперь отзыв
        идёт через ``transfer_county`` с ``new_holder_id=None``, то есть
        прежний держатель теряет ``province_idx``, становится безземельным, а
        контракт с новым сюзереном пересчитывается.

        Владелец нации при этом НЕ меняется: отзыв не отбирает землю у короля,
        он лишь забирает её у барона. Аннексия — это отдельное действие.

        ``by_actor`` (этап 1.1) — те же права, что у ``grant_fief``: живой
        сюзерен цели по рангу. Проверять тут особенно важно, потому что отзыв —
        самое разрушительное, что может сделать сюзерен, и раньше он был
        доступен кому угодно, кто знал id вассала.
        """
        ch = self.characters.get(baron_id)
        if ch is None:
            return []
        if by_actor is not None:
            refusal = self._command_refusal(self._actor_of(by_actor), ch)
            if refusal is not None:
                return [refusal]
        return self._revoke_fief_now(ch)

    def _revoke_fief_now(self, ch: Character) -> List[str]:
        """Ядро отзыва земли без проверки прав."""
        events: List[str] = []
        if ch.province_idx is not None:
            province_idx = ch.province_idx
            events += self.transfer_county(province_idx, self.nation_of(province_idx),
                                           None, cause="фьеф отозван")
        ch.province_idx = None
        ch.landless_turns = 0
        ch.opinion_of_liege = max(-100, ch.opinion_of_liege - 20)
        ch.loyalty = max(0, ch.loyalty - 20)
        events.append(f"{ch.name} лишён земли, мнение {ch.opinion_of_liege}")
        return events

    # ---------------- траты золота ----------------
    #
    # Шесть команд об одном контракте:
    #
    # * возвращают ``List[str]`` — журнал событий, как все остальные методы;
    # * неизвестная цель (нет персонажа/провинции/realm'а) -> пустой список,
    #   потому что клиенту нечего показывать, а лог не должен засоряться;
    # * известная цель, но отказ по существу (нет права, не хватает золота,
    #   исчерпан лимит) -> ОДНО событие с причиной: это то, что UI показывает
    #   игроку. Стиль тот же, что у ``set_contract``;
    # * ни одна не падает на мусорных входах (см. ``as_int``);
    # * лимит «раз за ход» проверяется ПОСЛЕДНИМ и тратится только при успехе,
    #   чтобы отказ по золоту не съедал право на действие.

    def raise_levy(self, realm_id: str, blocks: object) -> List[str]:
        """T1. Поднять левейс: сотни солдат вперёд, содержание — каждый ход.

        Потолок — весь левейс realm'а (``realm_levy``): поднятое не может
        превысить наличное. Остаток живёт в ``Realm.raised_levy`` и отдельной
        строкой попадает в ``realm_upkeep``.
        """
        realm = self.realms.get(realm_id) if isinstance(realm_id, str) else None
        if realm is None:
            return []
        actor = self._command_ruler(realm_id)
        if actor is None:
            return [f"{realm.name}: поднимать левейс некому"]
        count = as_int(blocks)
        if count is None or count <= 0:
            return [f"{realm.name}: левейс поднимают блоками по {LEVY_BLOCK_TROOPS}, "
                    f"а не «{blocks}»"]
        soldiers = count * LEVY_BLOCK_TROOPS
        levy_cap = self.realm_levy(realm_id)
        if realm.raised_levy + soldiers > levy_cap:
            return [f"{realm.name}: левейс исчерпан ({realm.raised_levy}/{levy_cap})"]
        cost = count * LEVY_COST_PER_BLOCK
        if realm.gold < cost:
            return [f"{realm.name}: не хватает золота на левейс "
                    f"(нужно {cost}, есть {realm.gold})"]
        if self._ledger_exhausted(actor.id, ACTION_RAISE_LEVY, LEVY_RAISES_PER_TURN):
            return [f"{actor.name}: левейс уже поднимали в этом ходу"]
        self._ledger_spend(actor.id, ACTION_RAISE_LEVY)
        realm.gold -= cost
        realm.raised_levy += soldiers
        return [f"{realm.name}: поднят левейс {soldiers} (казна {realm.gold})"]

    def develop_county(self, province_idx: int,
                       actor_id: Optional[str] = None) -> List[str]:
        """T2. Застроить графство: +1 development по линейной цене.

        Платит казна того королевства, которое ФАКТИЧЕСКИ владеет провинцией
        (``province.owner``), а не того, чьё это герцогство de jure: застройка
        идёт по факту владения, иначе можно было бы строить чужую землю.
        """
        if not isinstance(province_idx, int) or isinstance(province_idx, bool):
            return []
        if not 0 <= province_idx < len(self.provinces):
            return []
        province = self.province(province_idx)
        place = getattr(province, "name", f"#{province_idx}")
        realm_id = self.realm_owning(province_idx)
        if realm_id is None:
            return [f"{place}: нейтральная земля, строить некому"]
        realm = self.realms[realm_id]
        actor = self._command_ruler(realm_id, actor_id)
        if actor is None:
            return [f"{realm.name}: {place} не под его властью"]
        development = as_int(getattr(province, "development", 1))
        if development is None:
            return []
        if development >= DEVELOPMENT_MAX:
            return [f"{place}: застроен максимум ({DEVELOPMENT_MAX})"]
        cost = development_upgrade_cost(development)
        if realm.gold < cost:
            return [f"{realm.name}: не хватает золота на застройку "
                    f"(нужно {cost}, есть {realm.gold})"]
        if self._ledger_exhausted(actor.id, ACTION_DEVELOP, DEVELOPMENTS_PER_TURN):
            return [f"{actor.name}: застройка уже исчерпана на этот ход"]
        self._ledger_spend(actor.id, ACTION_DEVELOP)
        realm.gold -= cost
        province.development = development + 1
        return [f"{place}: застройка {development} → {province.development} "
                f"(казна {realm.gold})"]

    def gift_vassal(self, vassal_id: str) -> List[str]:
        """T3. Подарок вассалу: мнение и лояльность за 60 золота.

        Отдача падает по ``Character.gifts_received`` — ЗА ЖИЗНЬ, а не за ход,
        поэтому пять подарков реальны, шестой бессмыслен и отклоняется.
        Платит сюзерен: король — из казны realm'а, герцог — из личного кошеля
        (у него нет своего realm'а). Лимит — один подарок одному вассалу за ход.
        """
        vassal = self.characters.get(vassal_id) if isinstance(vassal_id, str) else None
        if vassal is None:
            return []
        if not vassal.alive:
            return [f"{vassal.name}: мёртвым подарки не дарят"]
        liege = self.liege_of(vassal.id)
        if liege is None:
            return [f"{vassal.name}: не вассал — подарок некому"]
        if not liege.alive:
            return [f"{vassal.name}: сюзерен мёртв"]
        opinion_gain = gift_gain(vassal.gifts_received, GIFT_OPINION_BY_COUNT)
        loyalty_gain = gift_gain(vassal.gifts_received, GIFT_LOYALTY_BY_COUNT)
        if opinion_gain <= 0 and loyalty_gain <= 0:
            return [f"{vassal.name}: отдача от подарков иссякла"]
        # подарок адресован конкретному вассалу: лимит на пару, а не на сюзерена
        action = f"{ACTION_GIFT}:{vassal.id}"
        if self._ledger_exhausted(liege.id, action, GIFTS_PER_TURN):
            return [f"{vassal.name}: подарок ему уже отправлен в этом ходу"]
        if not self._charge_purse(liege, GIFT_COST):
            return [f"{liege.name}: не хватает {GIFT_COST} золота на подарок "
                    f"{vassal.name}"]
        self._ledger_spend(liege.id, action)
        vassal.gifts_received += 1
        vassal.opinion_of_liege = min(100, vassal.opinion_of_liege + opinion_gain)
        vassal.loyalty = min(100, vassal.loyalty + loyalty_gain)
        return [f"{liege.name} → {vassal.name}: подарок №{vassal.gifts_received} "
                f"(+{opinion_gain} мнения, +{loyalty_gain} лояльности), "
                f"теперь {vassal.opinion_of_liege}/{vassal.loyalty}"]

    def raise_crown_authority(self, realm_id: str) -> List[str]:
        """T4. Поднять власть короны: 300 золота и 30 престижа за ступень.

        Потолок — ``MAX_CROWN_AUTHORITY``. Проверяются обе цены: золота без
        престижа не хватит так же, как престижа без золота.
        """
        realm = self.realms.get(realm_id) if isinstance(realm_id, str) else None
        if realm is None:
            return []
        actor = self._command_ruler(realm_id)
        if actor is None:
            return [f"{realm.name}: власть короны некому поднимать"]
        authority = as_int(realm.crown_authority)
        if authority is None:
            return []
        if authority >= MAX_CROWN_AUTHORITY:
            return [f"{realm.name}: власть короны уже предельна "
                    f"({MAX_CROWN_AUTHORITY})"]
        if realm.gold < CROWN_COST:
            return [f"{realm.name}: не хватает {CROWN_COST} золота на корону "
                    f"(есть {realm.gold})"]
        if realm.prestige < CROWN_PRESTIGE_COST:
            return [f"{realm.name}: не хватает {CROWN_PRESTIGE_COST} престижа "
                    f"(есть {realm.prestige})"]
        if self._ledger_exhausted(actor.id, ACTION_CROWN, CROWN_RAISES_PER_TURN):
            return [f"{actor.name}: власть короны уже поднимали в этом ходу"]
        self._ledger_spend(actor.id, ACTION_CROWN)
        realm.gold -= CROWN_COST
        realm.prestige -= CROWN_PRESTIGE_COST
        realm.crown_authority = authority + 1
        return [f"{realm.name}: власть короны {authority} → {realm.crown_authority}"]

    def set_tax_policy(self, realm_id: str, policy: object) -> List[str]:
        """T4b. Налоговая политика королевства. Тяжёлый налог — только при короне.

        ``tax_policy = 1`` снимает 2 лояльности с поселений за ход и 2
        стабильности с королевства, поэтому разрешён он только при
        ``crown_authority >= TAX_POLICY_CROWN_AUTHORITY``. Вне диапазона
        значение клампится — как в ``set_contract``.
        """
        realm = self.realms.get(realm_id) if isinstance(realm_id, str) else None
        if realm is None:
            return []
        actor = self._command_ruler(realm_id)
        if actor is None:
            return [f"{realm.name}: налоговую политику некому менять"]
        requested = as_int(policy)
        if requested is None:
            return [f"{realm.name}: налоговая политика должна быть числом"]
        value = max(TAX_POLICY_MIN, min(TAX_POLICY_MAX, requested))
        if value == realm.tax_policy:
            return [f"{realm.name}: налоговая политика уже {value}"]
        if value > 0 and realm.crown_authority < TAX_POLICY_CROWN_AUTHORITY:
            return [f"{realm.name}: тяжёлый налог требует короны "
                    f"{TAX_POLICY_CROWN_AUTHORITY}+ (сейчас {realm.crown_authority})"]
        if self._ledger_exhausted(actor.id, ACTION_TAX_POLICY,
                                  TAX_POLICY_CHANGES_PER_TURN):
            return [f"{actor.name}: налоговую политику уже меняли в этом ходу"]
        self._ledger_spend(actor.id, ACTION_TAX_POLICY)
        realm.tax_policy = value
        return [f"{realm.name}: налоговая политика {value}"]

    def hire_mercenaries(self, realm_id: str, blocks: object) -> List[str]:
        """T5. Нанять наёмников. Единственный потребитель ГПСЧ в экономике.

        Единственное место, где эта пьеса обращается к ``self.streams`` — и
        только потому, что игрок сам попросил случайность. Соль броска
        целочисленная (``turn * MERC_SALT_STRIDE + index``), тир возвращается
        в событии, но качество заранее не показывается: игрок платит за найм,
        а не за конкретный тир.
        """
        realm = self.realms.get(realm_id) if isinstance(realm_id, str) else None
        if realm is None:
            return []
        actor = self._command_ruler(realm_id)
        if actor is None:
            return [f"{realm.name}: наёмников не нанимает никто"]
        count = as_int(blocks)
        if count is None or count <= 0:
            return [f"{realm.name}: наёмники идут блоками по "
                    f"{MERC_COST_PER_BLOCK}, а не «{blocks}»"]
        if count > MERC_MAX_BLOCKS_PER_TURN:
            return [f"{realm.name}: за ход наймётся максимум "
                    f"{MERC_MAX_BLOCKS_PER_TURN} блоков наёмников"]
        cost = count * MERC_COST_PER_BLOCK
        if realm.gold < cost:
            return [f"{realm.name}: не хватает золота на наёмников "
                    f"(нужно {cost}, есть {realm.gold})"]
        if self._ledger_exhausted(actor.id, ACTION_HIRE_MERC, MERC_HIRES_PER_TURN):
            return [f"{actor.name}: наёмников уже нанимали в этом ходу"]
        self._ledger_spend(actor.id, ACTION_HIRE_MERC)
        realm.gold -= cost
        events: List[str] = []
        for index in range(count):
            salt = mercenary_salt(self.turn, index)
            tier = mercenary_tier(self.streams.derive(MERC_QUALITY_STREAM, salt))
            realm.mercenary_tiers.append(tier)
            events.append(f"{realm.name}: наёмник тира {tier} "
                          f"({MERC_BLOCK_TROOPS} солдат, блок {index + 1}/{count}), "
                          f"всего тиров: {len(realm.mercenary_tiers)}")
        return events

    def hire_garrison(self, province_idx: int, soldiers: object,
                      actor_id: Optional[str] = None) -> List[str]:
        """T6. Нанять гарнизон в провинцию, не превысив потолок стен.

        Солдаты сверх ``garrison_cap`` не берутся (берётся минимум из
        «сколько просят» и «сколько влезает»), плата пропорциональна
        содержанию той же сотни, и казна та, что реально владеет землёй.
        """
        if not isinstance(province_idx, int) or isinstance(province_idx, bool):
            return []
        if not 0 <= province_idx < len(self.provinces):
            return []
        province = self.province(province_idx)
        place = getattr(province, "name", f"#{province_idx}")
        realm_id = self.realm_owning(province_idx)
        if realm_id is None:
            return [f"{place}: нейтральная земля, гарнизон платить нечему"]
        realm = self.realms[realm_id]
        actor = self._command_ruler(realm_id, actor_id)
        if actor is None:
            return [f"{realm.name}: {place} не под его властью"]
        wanted = as_int(soldiers)
        if wanted is None or wanted <= 0:
            return [f"{place}: гарнизон нанимают солдатами, а не «{soldiers}»"]
        current = as_int(getattr(province, "garrison", 0)) or 0
        cap = self.garrison_cap(province_idx)
        taken = min(wanted, max(0, cap - current))
        if taken <= 0:
            return [f"{place}: гарнизон полон ({current}/{cap})"]
        cost = taken * GARRISON_RECRUIT_COST_PER_100 // 100
        if realm.gold < cost:
            return [f"{realm.name}: не хватает золота на гарнизон "
                    f"(нужно {cost}, есть {realm.gold})"]
        if self._ledger_exhausted(actor.id, ACTION_HIRE_GARRISON,
                                  GARRISON_HIRES_PER_TURN):
            return [f"{actor.name}: гарнизон уже нанимали в этом ходу"]
        self._ledger_spend(actor.id, ACTION_HIRE_GARRISON)
        realm.gold -= cost
        province.garrison = current + taken
        clipped = "" if taken == wanted else f", потолок {cap} (просили {wanted})"
        return [f"{place}: нанято {taken} солдат в гарнизон{clipped} "
                f"(всего {province.garrison}/{cap}, казна {realm.gold})"]

    # ---------------- приказы (этап 1.2) ----------------
    #
    # Контракт раздела:
    #
    # * ``issue_order`` — команда сюзерена. Проверяет право той же логикой, что и
    #   ``by_actor``, плюс осмысленность аргументов, и кладёт ``PENDING`` в
    #   ``self.orders``. Ничего не применяет: приказ живёт.
    # * ``resolve_orders`` — конец хода. ``PENDING`` получает решение вассала,
    #   просроченный ``ACCEPTED`` применяется.
    # * ``punish_order`` — команда сюзерена на ПРИНЯТЫЙ, но не исполненный
    #   приказ.
    # * ``summon_council`` — команда «приехать ко двору»; исполняет приказ
    #   ``SUMMON_COUNCIL``.
    #
    # Ни одна из них не обращается к ГПСЧ: решение выводится из мнения, чтобы
    # два одинаковых мира после одинаковой переписки приказов совпали по хешу.

    def _next_order_id(self) -> str:
        """Детерминированный id приказа: ``order_{ход}_{номер}``.

        Счётчик — ``len(self.orders)``, а не отдельное поле. Это работает,
        потому что приказы не удаляются никогда (см. ``__init__``), и заодно
        выживает round-trip без нового ключа в снапшоте: у загруженного мира
        ``len(orders)`` уже включает всё, что было до сохранения, поэтому новый
        id не может с ним столкнуться.
        """
        return f"order_{self.turn}_{len(self.orders)}"

    def issue_order(self, issuer_id: str, kind: object, target_id: str,
                    args: Optional[Dict[str, object]] = None) -> Optional[Order]:
        """Выдать приказ вассалу. ``None`` — права нет.

        Проверяется ровно то же, что проверяют команды с ``by_actor``: издатель
        обязан быть живым сюзереном цели по рангу. Сверх того проверяется
        осмысленность аргументов (``_order_args_refusal``): нельзя выдать
        приказ выдать графство в чужой земле или сменить контракт на
        несуществующий уровень — иначе вассал получил бы заведомо
        неисполнимый приказ, и его «отказ» ничего бы не значил.

        Лимит — ``ORDERS_ISSUED_PER_TURN`` на ВИД приказа (``action_ledger``).
        Приказ создаётся в статусе ``PENDING`` и ждёт ``resolve_orders``.

        Порядок проверок совпадает с порядком команд: неизвестный вид и
        неизвестная цель дают ``None`` молча (нечего показывать), отказ по
        существу — тоже ``None``, потому что вызывающий UI сам формирует текст
        из причины, а приказ в этом случае не создан.
        """
        resolved = order_kind_of(kind)
        if resolved is None:
            return None
        target = self.characters.get(target_id) if isinstance(target_id, str) else None
        if target is None:
            return None
        actor = self._actor_of(issuer_id)
        if self._command_refusal(actor, target) is not None:
            return None
        payload = clean_order_args(args)
        if self._order_args_refusal(resolved, actor, target, payload) is not None:
            return None
        action = f"{ACTION_ISSUE_ORDER}:{resolved.value}"
        if self._ledger_exhausted(actor.id, action, ORDERS_ISSUED_PER_TURN):
            return None
        self._ledger_spend(actor.id, action)
        order = Order(id=self._next_order_id(), kind=resolved, issuer_id=actor.id,
                      target_id=target.id, turn_issued=self.turn, args=payload,
                      status=OrderStatus.PENDING, resolved_turn=None,
                      message="ждёт решения")
        self.orders[order.id] = order
        return order

    def _order_args_refusal(self, kind: OrderKind, actor: Character,
                            target: Character,
                            args: Dict[str, object]) -> Optional[str]:
        """Осмысленность аргументов приказа на момент ВЫДАЧИ, а не исполнения.

        Золото и лояльность здесь не проверяются: к моменту исполнения (через
        ``ORDER_DEADLINE_TURNS``) они изменятся, и проверка стала бы ложью.
        Проверяется только то, что останется правдой: чья это земля, какой это
        уровень контракта и есть ли у цели что отзывать.
        """
        if kind is OrderKind.GRANT_FIEF:
            return self._grant_fief_refusal(actor.id, target,
                                            args.get("province_idx"))
        if kind is OrderKind.REVOKE_FIEF:
            if target.province_idx is None:
                return f"{target.name}: отзывать нечего, земли у него нет"
            return None
        if kind is OrderKind.SET_CONTRACT:
            level = as_int(args.get("level"))
            if level is None:
                return "уровень контракта должен быть числом"
            if not 0 <= level <= len(CONTRACT_LEVELS) - 1:
                return (f"уровень контракта {level} вне диапазона "
                        f"0..{len(CONTRACT_LEVELS) - 1}")
            return None
        if kind is OrderKind.RAISE_LEVY:
            realm = self._realm_of_ruler(actor)
            if realm is None:
                return f"{actor.name}: левейс поднимает только король"
            blocks = as_int(args.get("blocks"))
            if blocks is None or blocks <= 0:
                return f"левейс поднимают блоками по {LEVY_BLOCK_TROOPS}"
            if args.get("realm_id") is not None and args.get("realm_id") != realm.id:
                return f"{actor.name}: левейс его realm'а, а не чужого"
            return None
        if kind is OrderKind.DEVELOP_COUNTY:
            province_idx = args.get("province_idx")
            if not isinstance(province_idx, int) or isinstance(province_idx, bool) \
                    or not 0 <= province_idx < len(self.provinces):
                return f"застройка задаётся номером провинции, а не «{province_idx}»"
            realm = self._realm_of_actor(actor)
            if realm is None:
                return f"{actor.name}: у него нет королевства, чтобы застраивать"
            if getattr(self.province(province_idx), "owner", "neutral") != realm.nation:
                return f"{realm.name}: провинция #{province_idx} не под его властью"
            # платит казна того королевства, которому земля принадлежит по факту,
            # а ``develop_county`` разрешает тратить её только правителю realm'а,
            # поэтому заказать застройку может именно он — не герцог от лица
            # короны. Проверяем здесь, чтобы вассал не получил бы заведомо
            # неисполнимый приказ.
            if realm.ruler_id != actor.id:
                return (f"{actor.name}: застройку оплачивает и заказывает "
                        f"правитель {realm.name}")
            return None
        # SUMMON_COUNCIL и GIFT аргументов не требуют
        return None

    def order_of(self, vassal_id: str) -> Optional[Order]:
        """Последний ЖИВОЙ приказ этому вассалу (``None``, если таких нет).

        Удобно UI: показать вассалу один незакрытый приказ, а не весь список.
        Порядок — по ``id``, поэтому выбор детерминирован.
        """
        if not isinstance(vassal_id, str):
            return None
        for order_id in sorted(self.orders, reverse=True):
            order = self.orders[order_id]
            if order.target_id == vassal_id and order.is_open:
                return order
        return None

    def summon_council(self, actor_id: str, vassal_id: str) -> List[str]:
        """Созвать совет: вассал едет ко двору и получает влияние и лояльность.

        По смыслу CK3 — «summon to court». Это НЕ наказание, поэтому исполненный
        вызов награждает: ``+COUNCIL_INFLUENCE`` влияния (половина начального
        влияния барона, 10 — заметный, но не переломный шаг) и
        ``+COUNCIL_LOYALTY`` лояльности (ровно как первый подарок: совет ничего
        не стоит сюзерену в золоте и потому не должен стоить больше подарка).

        Отказ от приказа наносится НЕ здесь, а в ``resolve_orders``: он весит по
        ``ORDER_WEIGHTS``, а совет — самый лёгкий вид приказа (вес 1).

        Права те же, что у ``by_actor``: созвать совет может только живой
        сюзерен цели по рангу.
        """
        vassal = self.characters.get(vassal_id) if isinstance(vassal_id, str) else None
        if vassal is None:
            return []
        actor = self._actor_of(actor_id)
        refusal = self._command_refusal(actor, vassal)
        if refusal is not None:
            return [refusal]
        return self._council_now(vassal)

    def _council_now(self, vassal: Character) -> List[str]:
        """Ядро совета без проверки прав (см. ``_grant_fief_now``)."""
        vassal.influence = min(100, vassal.influence + COUNCIL_INFLUENCE)
        vassal.loyalty = min(100, vassal.loyalty + COUNCIL_LOYALTY)
        issuer = self.liege_of(vassal.id)
        return [f"{issuer.name if issuer else '?'} → {vassal.name}: совет во дворце "
                f"(+{COUNCIL_INFLUENCE} влияния, +{COUNCIL_LOYALTY} лояльности), "
                f"теперь {vassal.influence}/{vassal.loyalty}"]

    def resolve_orders(self, turn: Optional[int] = None) -> List[str]:
        """Конец хода: каждый приказ получает решение, принятое — исполняется.

        Три перехода, и только три:

        * ``PENDING`` -> ``ACCEPTED`` («вассал принял») либо ``REFUSED`` минус
          ``REFUSED_WEIGHT * вес приказа`` мнения. Решение выводится из
          ``can_accept_order``, то есть из мнения и веса, и НЕ бросает кубик;
        * ``ACCEPTED`` старше ``ORDER_DEADLINE_TURNS`` -> ``FULFILLED``: приказ
          применяется ядром команды сюзерена, и права перепроверяются заново (см.
          ``_apply_order``). Приказ хода ``N`` исполняется на границе
          ``N + ORDER_DEADLINE_TURNS``, то есть у вассала есть ровно
          ``ORDER_DEADLINE_TURNS`` полных ходов на подготовку;
        * ``ACCEPTED`` младше срока — просто ждёт. Это окно нужно сюзерену,
          чтобы успеть позвать ``punish_order``.

        Мёртвые с обеих сторон приказы закрываются как ``REFUSED`` с пустым
        штрафом: виноватых нет, а оставлять такой приказ в очереди навсегда
        нельзя — тогда ``resolve_orders`` перестанет быть чистой функцией
        состояния.

        Обход строго по отсортированным ``id``, чтобы порядок событий не зависел
        от порядка выдачи приказов (он зависит от команд игрока, а не от хеша).
        """
        current = self.turn if turn is None else int(turn)
        events: List[str] = []
        for order_id in sorted(self.orders):
            order = self.orders[order_id]
            if not order.is_open:
                continue
            issuer = self.characters.get(order.issuer_id)
            target = self.characters.get(order.target_id)
            label = self._order_label(order)
            if issuer is None or not issuer.alive or target is None or not target.alive:
                order.status = OrderStatus.REFUSED
                order.resolved_turn = current
                order.message = "приказ снят: сюзерен или вассал мёртв"
                events.append(f"{label}: снят, никто не может его исполнить")
                continue
            if order.status is OrderStatus.PENDING:
                if self.can_accept_order(target.id, order):
                    order.status = OrderStatus.ACCEPTED
                    order.resolved_turn = current
                    order.message = "вассал принял"
                    events.append(f"{label}: принят, ждёт исполнения")
                else:
                    order.status = OrderStatus.REFUSED
                    order.resolved_turn = current
                    order.message = "вассал отказался"
                    target.opinion_of_liege = max(
                        -100, target.opinion_of_liege - order.refusal_penalty)
                    events.append(f"{label}: отказ, мнение {target.opinion_of_liege} "
                                  f"(-{order.refusal_penalty})")
                continue
            # ACCEPTED: исполняем, когда срок вышел
            if current - order.turn_issued < ORDER_DEADLINE_TURNS:
                continue
            applied, applied_events = self._apply_order(order)
            order.status = OrderStatus.FULFILLED
            order.resolved_turn = current
            order.message = "исполнен" if applied else "не исполнен"
            events.append(f"{label}: {order.message}")
            if applied:
                events += applied_events
        return events

    def _order_label(self, order: Order) -> str:
        """Короткая подпись приказа для журнала: ``приказ {id} ({вид})``."""
        issuer = self.characters.get(order.issuer_id)
        target = self.characters.get(order.target_id)
        return (f"приказ {order.id} ({order.kind.value}) "
                f"{issuer.name if issuer else '?'} → "
                f"{target.name if target else '?'}")

    def _apply_order(self, order: Order) -> Tuple[bool, List[str]]:
        """Применить принятый приказ. ``False`` — условия приказа сорвались.

        Условия проверяются ОДНОЙ функцией с ``issue_order``
        (``_order_args_refusal``) плюс общей проверкой прав: за
        ``ORDER_DEADLINE_TURNS`` земля могла сменить владельца, а получатель —
        получить другое графство. Приказ, который нельзя исполнить, честно
        закрывается как «не исполнен» с причиной в журнале.

        Применение идёт ЯДРАМИ (``_grant_fief_now``, ``_revoke_fief_now``,
        ``_set_contract_now``, ``_council_now``), а не публичными командами, и
        поэтому НЕ тратит ``action_ledger``: «одна смена контракта за ход»
        относится к живой кнопке сюзерена, а не к разбирательству по ранее
        выданному приказу. Иначе король, кликнувший кнопку в этом же ходу,
        мог бы тихо похоронить собственный приказ — и «приказ висит» стало бы
        синонимом «игрок нажал не туда».

        Отказ САМОЙ команды-траты (нет золота, левейс исчерпан, подарки иссякли)
        не делает приказ неисполненным: условия приказа были в порядке, срок
        вышел. Хочешь повторить — выдай новый приказ.
        """
        issuer = self.characters.get(order.issuer_id)
        target = self.characters.get(order.target_id)
        if issuer is None or not issuer.alive or target is None or not target.alive:
            return False, []
        label = self._order_label(order)
        refusal = self._command_refusal(issuer, target)
        if refusal is None:
            refusal = self._order_args_refusal(order.kind, issuer, target, order.args)
        if refusal is not None:
            return False, [f"{label}: не исполнен — {refusal}"]
        args = order.args
        if order.kind is OrderKind.SUMMON_COUNCIL:
            events = self._council_now(target)
        elif order.kind is OrderKind.GIFT:
            events = self.gift_vassal(target.id)
        elif order.kind is OrderKind.GRANT_FIEF:
            events = self._grant_fief_now(as_int(args.get("province_idx")), target)
        elif order.kind is OrderKind.REVOKE_FIEF:
            events = self._revoke_fief_now(target)
        elif order.kind is OrderKind.SET_CONTRACT:
            events = self._set_contract_now(target.id, as_int(args.get("level")) or 0)
        elif order.kind is OrderKind.RAISE_LEVY:
            realm = self._realm_of_ruler(issuer)
            if realm is None:
                return False, []
            events = self.raise_levy(realm.id, args.get("blocks", 1))
        elif order.kind is OrderKind.DEVELOP_COUNTY:
            events = self.develop_county(as_int(args.get("province_idx")), issuer.id)
        else:
            return False, []
        return True, events

    def punish_order(self, order_id: str, *,
                     by_actor: Optional[str] = None) -> List[str]:
        """Наказать вассала за неисполненный приказ: минус мнение и лояльность.

        Схема неисполнения выбрана простая: **приказ не висит вечно, но и не
        применяется сам**. ``resolve_orders`` закрывает просроченный ``ACCEPTED``
        либо исполнением, либо оставляет его сюзерену решать — то есть сначала
        «вассал обещал» (ACCEPTED), затем либо «сделал» (FULFILLED), либо «с
        него спросили» (PUNISHED). Молчаливое игнорирование приказа было бы
        худшим вариантом из трёх: у него нет ни автора, ни последствий.

        Наказать можно только пока приказ ``ACCEPTED``: отказённый не
        обещал, исполненный уже нечего наказывать. ``by_actor`` — та же проверка
        прав, что и везде; ``None`` — прежний стиль вызовов.
        """
        order = self.orders.get(order_id) if isinstance(order_id, str) else None
        if order is None:
            return []
        if order.status is not OrderStatus.ACCEPTED:
            return [f"приказ {order.id}: наказать нечего "
                    f"(статус {order.status.value})"]
        target = self.characters.get(order.target_id)
        if target is None or not target.alive:
            return [f"приказ {order.id}: наказывать некого"]
        if by_actor is not None:
            refusal = self._command_refusal(self._actor_of(by_actor), target)
            if refusal is not None:
                return [refusal]
        order.status = OrderStatus.PUNISHED
        order.resolved_turn = self.turn
        order.message = "наказан за неисполнение"
        target.opinion_of_liege = max(-100, target.opinion_of_liege + PUNISHED_OPINION)
        target.loyalty = max(0, target.loyalty - PUNISHED_LOYALTY)
        return [f"приказ {order.id}: {target.name} наказан за неисполнение "
                f"({PUNISHED_OPINION} мнения, -{PUNISHED_LOYALTY} лояльности), "
                f"теперь {target.opinion_of_liege}/{target.loyalty}"]

    # ---------------- конец хода ----------------

    def prosperity_cap(self, province_idx: int) -> int:
        """Потолок процветания: богатое поселение растёт до большего предела."""
        p = self.province(province_idx)
        return min(100, 20 + max(0, getattr(p, "hearths", 0)) // 20)

    def tick_counties(self) -> List[str]:
        """Лояльность поселений: гарнизон и налоги давят, мир поднимает.

        Равновесие без гарнизона — около 55 лояльности (поселение не
        умирает, но и не процветает); с гарнизоном лояльность растёт до
        100. Поэтому гарнизон стоит денег (см. ``garrison_upkeep``), а его
        отсутствие не убивает поселение, но лишает его полного дохода.

        Здесь же — атриция гарнизонов. Проверка «может ли королевство
        заплатить» делается по золоту, которое доступно **на момент входа
        в фазу**: порядок ``end_turn`` такой (``tick_counties`` ->
        ``tick_vassals`` -> ``tick_realms``), поэтому здесь видно золото
        ПРОШЛОГО хода, а текущий доход ещё не начислен. Это нормально и
        полностью детерминировано — простое сравнение с золотом после
        начисления зависело бы от ``tick_realms``, который ещё не шёл.
        """
        events: List[str] = []
        # индекс нация -> королевство: иначе на каждую провинцию пришлось бы
        # перебирать все realm'ы. Строится заново каждый тик, чтобы внешний
        # код мог спокойно перекрашивать карту между ходами.
        realm_of_nation = {realm.nation: realm_id for realm_id, realm in self.realms.items()}
        # казна прошлого хода: не хватило — гарнизон гниёт
        broke = {realm_id for realm_id in self.realms
                 if self.realms[realm_id].gold < self.garrison_upkeep(realm_id)}
        for idx, p in enumerate(self.provinces):
            loyalty = getattr(p, "loyalty", 70)
            garrison = getattr(p, "garrison", 0)
            prosperity = getattr(p, "prosperity", 0)
            security = getattr(p, "security", 10)

            # атриция: казна не тянет содержание — гарнизон рассыпается
            realm_id = realm_of_nation.get(getattr(p, "owner", None))
            if garrison > 0 and realm_id is not None and realm_id in broke:
                garrison = max(0, garrison - GARRISON_ATTRITION)
                p.garrison = garrison
                if garrison == 0:
                    events.append(f"Гарнизон #{idx} рассыпался: казна пуста")

            if garrison > 0:
                loyalty += 2
            elif loyalty > 55:
                loyalty -= 2
            else:
                # крестьяне сами возвращаются к хозяйству, если не давить
                loyalty += 1

            # высокие налоги (королевская политика) давят на populous county
            for realm in self.realms.values():
                if realm.tax_policy > 0 and getattr(p, "owner", None) == realm.nation:
                    loyalty -= 2
            loyalty = max(0, min(100, loyalty))

            # процветание упирается в население, иначе экономика уходит в инфляцию
            cap = self.prosperity_cap(idx)
            if prosperity < cap:
                prosperity += 1 if loyalty >= 60 else -1
            prosperity = max(0, min(cap, prosperity))
            security = max(0, min(20, security + (1 if garrison > 0 else -1)))

            if loyalty < REBELLION_LOYALTY:
                events.append(f"Мятеж в #{idx}: лояльность {loyalty}")

            p.loyalty = loyalty
            p.prosperity = prosperity
            p.security = security
            # застройка растёт только при образцовом порядке
            if loyalty >= 80 and getattr(p, "development", 1) < 5:
                p.development = getattr(p, "development", 1) + 1
            elif loyalty < 40 and getattr(p, "development", 1) > 1:
                p.development = getattr(p, "development", 1) - 1
        return events

    # ---------------- старение, смерть, наследование (этап 4) ----------------
    #
    # Контракт раздела:
    #
    # * ``tick_characters`` — единственный вызов старения и смертей. Живёт в
    #   ``end_turn`` последней фазой, чтобы экономика хода считалась по миру,
    #   в котором все ещё живы.
    # * ``kill_character`` — явная смерть (бой, яд, казнь). Детерминирована так
    #   же, как старение: причина передаётся строкой, кубик не бросается.
    # * ``settle_deaths`` — разбирает титулы умерших: realm -> герцогство ->
    #   графство, в этом порядке, потому что преемник герцогства сам может
    #   оказаться безземельным бароном.
    # * ``auto_inherit`` (модульная функция) — обёртка над ``settle_deaths`` для
    #   внешних вызовов; раньше она была написана и не вызывалась НИ ОДНОЙ
    #   строкой кода, то есть наследования в игре не было вообще.

    def heir_candidates(self, realm_id: str) -> List[Character]:
        """Преемники трона ``realm_id`` — по убыванию ``(-loyalty, -martial, id)``.

        Лояльность — главный критерий, военная сила — второй, id — третий
        (гарантия детерминизма: при равной лояльности и одинаковом ``martial``
        мир обязан выбрать одного и того же человека на всех машинах).

        Кандидаты — живые персонажи нации королевства. Ранг не фильтруется:
        ``tick_vassals`` держит лояльность примерно одинаковой у всех, так что
        ранг в сортировке ничего не решал бы, а фильтровать его — значило бы
        запретить престолу перейти к барону, который всю жизнь верно служил.
        Полноценная родословная по крови отложена (см. ``Character.heir``).
        """
        realm = self.realms.get(realm_id) if isinstance(realm_id, str) else None
        if realm is None:
            return []
        out = [c for c in self.characters.values()
               if c.alive and c.nation == realm.nation]
        out.sort(key=lambda c: (-c.loyalty, -c.martial, c.id))
        return out

    def duchy_heirs(self, duchy_id: str, *,
                    exclude: Optional[str] = None) -> List[Character]:
        """Преемники герцогства: живые персонажи той же дукции, ``(-loyalty, id)``.

        Порядок без ``-martial`` (как в прежней ``auto_inherit``): для
        герцогства важна преданность, а не боевая сила, и добавление третьего
        ключа здесь ничего бы не изменило — на карте у всех ``martial == 5``.

        Кандидаты ограничены НАЦИЕЙ нынешнего держателя. Это не украшение, а
        условие согласованности: дукция de jure принадлежит династии, и если бы
        преемником мог стать кто угодно, то ``nation`` нового герцога разошёлся
        бы с ``Duchy.realm_id``, который по-прежнему указывает на realm прежней
        нации. Титул и его страна обязаны ехать вместе.
        """
        out = [c for c in self.characters.values()
               if c.alive and c.duchy_id == duchy_id and c.id != exclude]
        nation = self.dynasty_nation_of_duchy(duchy_id)
        if nation is not None:
            out = [c for c in out if c.nation == nation]
        out.sort(key=lambda c: (-c.loyalty, c.id))
        return out

    def dynasty_nation_of_duchy(self, duchy_id: str) -> Optional[str]:
        """Нация династии герцогства — по de jure держателю (``Duchy.realm_id``).

        Титул и его страна обязаны ехать вместе, поэтому наследование
        герцогства ограничено этой нацией (см. ``duchy_heirs``). Если держателя
        нет, берётся нация realm'а самого герцогства, а если нет и его — ``None``,
        и тогда кандидатов не фильтруем: мир и так уже вне закона.
        """
        duchy = self.duchies.get(duchy_id)
        if duchy is None:
            return None
        holder = self.characters.get(duchy.holder_id or "")
        if holder is not None:
            return holder.nation
        realm = self.realms.get(duchy.realm_id or "")
        return realm.nation if realm is not None else None

    def county_heirs(self, province_idx: int, *,
                     exclude: Optional[str] = None) -> List[Character]:
        """Преемники графства: живые БЕЗЗЕМЕЛЬНЫЕ БАРОНЫ его нации, ``(-loyalty, id)``.

        Два ограничения, и оба обязательные:

        * **нация.** Держатель графства и ``province.owner`` обязаны совпадать:
          если разойдутся, налог пойдёт одной стране, а землёй будет владеть
          персонаж другой, и ``realm_income`` с ``duchy_income`` начнут считать
          разные вещи.
        * **ранг барона.** Графство — это владение барона; наследование от
          умершего сюзерена (``grant_fief``) может подарить графство и герцогу,
          а смерть барона не может выдать землю ни королю, ни чужому герцогу —
          тот иначе получил бы «собственное графство», которого у него и так
          нет в ``is_ruler``.

        Порядок детерминирован, повторный вызов даёт тот же список.
        """
        nation = self.nation_of(province_idx)
        out = [c for c in self.characters.values()
               if c.alive and c.nation == nation and c.rank is TitleRank.BARON
               and c.province_idx is None and c.id != exclude]
        out.sort(key=lambda c: (-c.loyalty, c.id))
        return out

    def succession_crisis_of(self, realm_id: str) -> Optional[SuccessionCrisis]:
        return self.succession_crises.get(realm_id) \
            if isinstance(realm_id, str) else None

    def open_succession_crisis(self, realm_id: str) -> SuccessionCrisis:
        """Открыть (или переоткрыть) кризис престола королевства.

        Запись всегда создаётся, даже если преемников нет: «у королевства нет
        правителя» — это факт, который обязан быть виден в панели и в хеше, а не
        молчаливый ``ruler_id = None``. Если кандидат есть, трон занимает
        ``candidates[0]`` — выбор детерминирован, чтобы реплей сервера
        совпадал. Игрок может переопределить его через
        ``resolve_succession`` (см. там же про формат выбора).
        """
        realm = self.realms.get(realm_id)
        if realm is None:
            raise ValueError(f"нет королевства {realm_id!r}")
        candidates = [c.id for c in self.heir_candidates(realm_id)]
        crisis = SuccessionCrisis(
            realm_id=realm_id,
            candidates=tuple(candidates),
            turn_opened=self.turn,
            turn_limit=self.turn + SUCCESSION_CRISIS_TURNS,
        )
        if candidates:
            heir = self.characters[candidates[0]]
            realm.ruler_id = heir.id
            heir.realm_id = realm_id
            heir.rank = TitleRank.KING
            crisis.ruler_id = heir.id
            crisis.resolved_turn = self.turn
        else:
            realm.ruler_id = None
        self.succession_crises[realm_id] = crisis
        return crisis

    def resolve_succession(self, realm_id: str, character_id: str) -> List[str]:
        """Явный выбор преемника из кандидатов кризиса (точка для игрока).

        Формат выбора: ``character_id`` обязан быть в ``crisis.candidates`` и
        быть жив. Никаких прав не проверяется — престол нельзя «выиграть»
        командой, его можно только раздать одному из названных кандидатов; кто
        именно нажимает — забота вызывающего слоя (UI или сетевой команды).

        Трон немедленно занимает кандидат, ``crisis`` закрывается записью
        ``ruler_id``/``resolved_turn``, поэтому в снапшоте видно, КТО сел и
        КОГДА. На ранг преемника это не влияет: он и так получает ``KING`` при
        назначении (см. ``open_succession_crisis``).
        """
        crisis = self.succession_crisis_of(realm_id)
        realm = self.realms.get(realm_id) if isinstance(realm_id, str) else None
        if crisis is None or realm is None:
            return []
        if character_id not in crisis.candidates:
            return [f"{realm.name}: {character_id} не числится преемником"]
        heir = self.characters.get(character_id)
        if heir is None or not heir.alive:
            return [f"{realm.name}: преемник {character_id} нежив"]
        if crisis.ruler_id == character_id:
            return [f"{realm.name}: {heir.name} уже на троне"]
        realm.ruler_id = heir.id
        heir.realm_id = realm_id
        heir.rank = TitleRank.KING
        crisis.ruler_id = heir.id
        crisis.resolved_turn = self.turn
        return [f"{realm.name}: престол занимает {heir.name} "
                f"(прежний: {crisis.candidates[0] if crisis.candidates else '—'})"]

    def kill_character(self, character_id: str, *, cause: str = DEATH_CAUSE_KILLED) -> List[str]:
        """Убить персонажа и разобрать его титулы (детерминированно, без кубика).

        Точка входа для ``war.py``: генерала или правителя можно снять сразу, не
        дожидаясь старости. Разбор титулов делает ``settle_deaths``, поэтому
        смерть на поле боя и смерть от старости дают одинаковые последствия —
        иначе «убили герцога» и «герцог умер» были бы разными механиками.
        """
        ch = self.characters.get(character_id) if isinstance(character_id, str) else None
        if ch is None or not ch.alive:
            return []
        ch.alive = False
        return [f"{ch.name} ({cause}, {ch.age} лет)"] + self.settle_deaths([ch])

    def settle_deaths(self, dead: Sequence[Character] = ()) -> List[str]:
        """Разобрать титулы умерших: realm -> герцогство -> графство.

        Порядок важен и единственный: сначала престол, потом герцогство, потом
        графство. Наоборот нельзя — новый герцог, только что получивший дукцию,
        тут же должен быть в состоянии «с дукцией», когда решается судьба
        графства.

        Что происходит с каждым титулом:

        * **Трон.** ``Realm.ruler_id`` переходит преемнику из
          ``heir_candidates`` (``-loyalty``, ``-martial``, ``id``), преемник
          получает ранг ``KING`` и ``realm_id``. Если преемников нет —
          ``ruler_id = None`` и открывается ``SuccessionCrisis``: явное
          состояние, а не тихий баг.
        * **Герцогство.** ``Duchy.holder_id`` переходит живому персонажу той
          же дукции, наследник получает ранг ``DUKE`` и ``realm_id`` герцогства.
          Если наследников нет — ``holder_id = None`` и явное событие: в UI не
          должен появиться труп правителем (именно это и делал
          ``holder_of_duchy``, не проверяя ``alive``).
        * **Графство.** Если у умершего было ``province_idx``, поле
          обнуляется ВСЕГДА (иначе на графстве окажутся двое), а само графство
          переходит живому барону той же нации (тот же порядок отбора). Если
          наследников нет — пишется событие «графство осталось без хозяина»:
          земля возвращается в пул, а её налог остаётся у нации, потому что
          ``owner`` не менялся.
        * **Контракты.** У мёртвого контракт удаляется (вассал мёртв — платить
          некому), у наследника — пересчитывается под нового сюзерена.

        УМЕРШИЙ НЕ ТЕРЯЕТ НИЧЕГО, ЧТО НЕ СВЯЗАНО С ЕГО ТИТУЛАМИ: ``duchy_id``
        остаётся, если герцогство ушло к наследнику иначе (``transfer_county``
        и ``_sync_contract`` идут по своим путям). Сохранять это важно для
        истории снапшота: по ``duchy_id`` мёртвого видно, кем он был.
        """
        if not dead:
            return []
        events: List[str] = []
        gone = {ch.id for ch in dead}
        # 1. престол
        for realm_id in sorted(self.realms):
            realm = self.realms[realm_id]
            if realm.ruler_id is None or realm.ruler_id not in gone:
                continue
            old_ruler = self.characters.get(realm.ruler_id or "")
            old_name = old_ruler.name if old_ruler else "?"
            crisis = self.open_succession_crisis(realm_id)
            if crisis.ruler_id:
                heir = self.characters[crisis.ruler_id]
                self._sync_contract(heir)
                events.append(f"{realm.name}: престол перешёл к {heir.name} "
                              f"(прежний {old_name})")
            else:
                events.append(f"{realm.name}: престол пуст, преемников нет")
        # 2. герцогства
        for duchy_id in sorted(self.duchies):
            duchy = self.duchies[duchy_id]
            if duchy.holder_id is None or duchy.holder_id not in gone:
                continue
            dead_holder = self.characters.get(duchy.holder_id or "")
            heirs = self.duchy_heirs(duchy_id, exclude=duchy.holder_id)
            if heirs:
                heir = heirs[0]
                duchy.holder_id = heir.id
                heir.rank = TitleRank.DUKE
                if duchy.realm_id:
                    heir.realm_id = duchy.realm_id
                self.refresh_rank(heir.id)
                self._sync_contract(heir)
                events.append(f"{duchy.name}: герцогом стал {heir.name}")
            else:
                duchy.holder_id = None
                events.append(f"{duchy.name}: герцогство осталось без герцога")
            if dead_holder is not None:
                events.append(f"{dead_holder.name} больше не герцог {duchy.name}")
        # 3. графства
        for ch in sorted(dead, key=lambda c: c.id):
            if ch.province_idx is None:
                continue
            province_idx = ch.province_idx
            # поле обнуляется ВСЕГДА, даже если нашёлся наследник: иначе на
            # одном графстве окажутся двое (``holder_of_county`` вернул бы
            # первого по id, то есть не того, кто на самом деле им владеет),
            # а мёртвый персонаж продолжал бы числиться правителем.
            ch.province_idx = None
            heirs = self.county_heirs(province_idx, exclude=ch.id)
            if heirs:
                heir = heirs[0]
                heir.province_idx = province_idx
                heir.landless_turns = 0
                if heir.duchy_id is None:
                    heir.duchy_id = self.duchy_of(province_idx)
                self.refresh_rank(heir.id)
                self._sync_contract(heir)
                events.append(f"графство #{province_idx} унаследовал {heir.name}")
            else:
                events.append(f"графство #{province_idx} осталось без хозяина")
        # 4. контракты. Смена ДЕРЖАТЕЛЯ герцогства меняет сюзерена сразу у всех
        # баронов дукции, поэтому контракты пересчитываются у ВСЕХ персонажей,
        # а не только у затронутых напрямую: иначе «мой вассал по контракту»
        # и «мой вассал по liege_of» снова разошлись бы. create=False — набор
        # контрактов не должен зависеть от того, кто умер.
        for ch in sorted(self.characters.values(), key=lambda c: c.id):
            if ch.id in gone:
                self.contracts.pop(ch.id, None)
                continue
            self._sync_contract(ch, create=False)
        # 5. de-факто владельцы обязаны перестать называть трупы. Пока герцог
        # жив, его дукция указывала на него; после смерти поле пересчитывается
        # целиком (десять герцогств, копейки) — иначе в снапшоте остался бы
        # «правитель», который мёртв, и hash разошёлся бы с тем, что видит UI.
        self.recompute_de_facto_holders()
        return events

    def tick_characters(self) -> List[str]:
        """Старение, естественная смерть и разбор титулов (детерминированно).

        Вызывается из ``end_turn`` последней фазой — после экономики. Порядок
        объясним: ход считается по миру, в котором все персонажи ещё живы, а
        умершие влияют уже на следующий. Это заметно для ``realm_upkeep``:
        мёртвый король не должен успеть «списать» содержание двора.

        Старение целочисленное и БЕЗ ГПСЧ — см. ``CHARACTERS_AGE_PER_TURN`` и
        ``CHARACTER_DEATH_AGE``. Ни одного обращения к ``self.streams``.
        """
        events: List[str] = []
        dead: List[Character] = []
        for ch in sorted(self.characters.values(), key=lambda c: c.id):
            if not ch.alive:
                continue
            ch.age += CHARACTERS_AGE_PER_TURN
            if ch.age >= ch.death_age:
                ch.alive = False
                dead.append(ch)
                events.append(f"{ch.name} умер {DEATH_CAUSE_AGE} ({ch.age} лет)")
        if dead:
            events += self.settle_deaths(dead)
        return events

    def tick_vassals(self) -> List[str]:
        """Мнение, лояльность, тирания, накопление недовольства."""
        events: List[str] = []
        for ch in sorted(self.characters.values(), key=lambda c: c.id):
            if not ch.alive:
                continue
            contract = self.contracts.get(ch.id)
            liege = self.liege_of(ch.id)
            if liege is None:
                continue

            if ch.is_ruler:
                ch.landless_turns = 0
            else:
                ch.landless_turns += 1
                ch.opinion_of_liege = max(-100, ch.opinion_of_liege - LANDLESS_OPINION_DECAY)

            if contract:
                ch.opinion_of_liege = max(
                    -100, ch.opinion_of_liege - contract.spec["tyranny"] // 2)

            # лояльность = мнение + авторитет сюзерена + личная преданность
            authority = self.liege_authority(ch.id)
            target = 30 + authority * 15 + ch.opinion_of_liege // 2
            if ch.loyalty < target:
                ch.loyalty = min(100, ch.loyalty + 3)
            else:
                ch.loyalty = max(0, ch.loyalty - 2)

            if ch.loyalty < VASSAL_REBELLION_LOYALTY:
                events.append(f"{ch.name} (лояльность {ch.loyalty}) готовит мятеж")
        return events

    def realm_upkeep(self, realm_id: str) -> int:
        """Содержание королевства: левейс на стену, двор вассалов, гарнизоны.

        Из чего складывается:

        * левейс realm'а, делённый на ``LEVY_UPKEEP_DIVISOR``;
        * ``COURT_COST_PER_VASSAL`` за каждого прямого вассала правителя;
        * содержание гарнизонов **этого** королевства (см.
          ``garrison_upkeep``) — гарнизон больше не бесплатный;
        * содержание ПОДНЯТОГО левейса (см. ``raise_levy``) — 8 золота за
          сотню за ход. Это обратная сторона траты T1: поднять левейс дёшево,
          держать его — не дёшево, иначе копил бы бесконечно;
        * ``ROYAL_COURT_BASE_COST`` плюс ``престиж // 10`` — блестящий
          двор дороже содержать, поэтому престиж стал стоком, а не
          мёртвым числом.
        """
        realm = self.realms[realm_id]
        upkeep = self.realm_levy(realm_id) // LEVY_UPKEEP_DIVISOR
        upkeep += max(0, as_int(realm.raised_levy) or 0) // RAISED_LEVY_UPKEEP_DIVISOR
        ruler = realm.ruler_id
        if ruler:
            upkeep += COURT_COST_PER_VASSAL * len(self.vassals_of(ruler))
        upkeep += self.garrison_upkeep(realm_id)
        return upkeep + ROYAL_COURT_BASE_COST + max(0, realm.prestige) // \
            ROYAL_COURT_PRESTIGE_DIVISOR

    def tick_realms(self) -> List[str]:
        """Казна королевств: доход минус содержание левейса и двора."""
        events: List[str] = []
        for realm in sorted(self.realms.values(), key=lambda r: r.id):
            income = self.realm_income(realm.id)
            upkeep = self.realm_upkeep(realm.id)
            realm.gold = max(0, realm.gold + income - upkeep)
            if income < upkeep:
                realm.stability = max(0, realm.stability - 2)
            # престиж растёт от владений и падает от пустого королевства
            held = len(self.provinces_of_realm(realm.id))
            if held >= 5:
                realm.prestige = min(100, realm.prestige + 1)
            elif held == 0:
                realm.prestige = max(0, realm.prestige - 2)
            # низкая стабильность от слишком высоких налогов
            if realm.tax_policy > 0:
                realm.stability = max(0, realm.stability - 2)
            else:
                realm.stability = min(100, realm.stability + 1)
        return events

    def end_turn(self) -> List[str]:
        """Один ход экономики. Порядок фиксирован — детерминизм для онлайна.

        Ни одна из фаз не обращается к ``self.streams``: ход — чистая
        функция состояния, поэтому хеш мира не «дрожет» от того, откуда
        взялись случайные числа. Броски живут только в командах.

        Разбор приказов стоит в конце цепочки и вызывается **только если
        приказы есть**. Это не микрооптимизация, а требование совместимости:
        ``end_turn`` обязана вести себя ровно как раньше, пока приказов не
        выдавали, иначе 532 теста прошлых этапов (включая проверки числа
        событий и детерминизма по хешу) разъедутся на пустом месте. При пустом
        ``orders`` ``resolve_orders`` всё равно вернул бы ``[]``, но явная
        охрана делает это свойство видимым в коде, а не «случайно так вышло».

        Здесь же обнуляется ``action_ledger``: лимиты «раз за ход» действуют
        внутри хода, а номер хода в ключе журнала нужен только для логов.
        Обнуление делает каноническую точку сохранения (границу хода)
        единственной точкой, где журнал гарантированно пуст. Обнуление выполняется
        ДВАЖДЫ: перед разбором приказов и после него. Первое — потому что
        разбор не должен отнимать у сюзерена его «раз за ход» живой кнопки
        (иначе ранее выданный приказ мог бы не исполниться только потому, что
        король в этом ходу уже кликнул ту же кнопку), второе — чтобы каноническая
        точка сохранения осталась с ПУСТЫМ журналом.

        Старение и смерть (``tick_characters``) стоят ПОСЛЕДНЕЙ фазой, перед
        увеличением ``turn``. Это требование совместимости, а не украшение:
        экономика хода обязана считаться по миру, в котором все персонажи ещё
        живы — иначе мёртвый король «спишет» содержание двора за этот ход и
        наследование начнёт влиять на экономику того же хода, а не следующего.
        Побочный эффект, который кстати: первая смерть на текущей карте случается
        на 38-м ходу (короли стартуют в 44 года, минимальный порог — 80), поэтому
        проверки «30 ходов подряд» и «100 ходов подряд» проходят без изменения их
        смысла, а к 200 ходам уже видны и смерть короля, и передача престола.
        """
        events: List[str] = []
        events += self.tick_counties()
        events += self.tick_vassals()
        events += self.tick_realms()
        closing_turn = self.turn
        self.action_ledger.clear()
        if self.orders:
            events += self.resolve_orders(closing_turn)
        events += self.tick_characters()
        self.turn += 1
        self.action_ledger.clear()
        self._append_log(events)
        return events

    def rebellions(self) -> List[str]:

        """Кто реально может поднять мятеж (лояльность < порога)."""
        out: List[str] = []
        for ch in sorted(self.characters.values(), key=lambda c: c.id):
            if ch.alive and ch.rank is not TitleRank.KING and ch.loyalty < VASSAL_REBELLION_LOYALTY:
                out.append(ch.id)
        return out

    def summary(self) -> Dict[str, object]:
        """Компактный слепок состояния — для UI, логов и хеша."""
        return {
            "turn": self.turn,
            "realms": {r.id: {"gold": r.gold, "prestige": r.prestige,
                              "stability": r.stability, "held": len(self.provinces_of_realm(r.id))}
                       for r in sorted(self.realms.values(), key=lambda x: x.id)},
            "duchies": {d.id: {"holder": d.holder_id, "income": self.duchy_income(d.id)}
                        for d in sorted(self.duchies.values(), key=lambda x: x.id)},
            "characters": {c.id: {"rank": c.rank.value, "loyalty": c.loyalty,
                                  "opinion": c.opinion_of_liege, "gold": c.gold}
                           for c in sorted(self.characters.values(), key=lambda x: x.id)},
        }

    # ---------------- сериализация состояния ----------------

    def to_state(self) -> Dict[str, object]:
        """Снапшот состояния в виде plain-dict, пригодный для хеша и JSON.

        Возвращаемый словарь — единственный честный представитель мира:
        ``sim.hashing.state_hash`` и ``sim.serialization.to_jsonable`` умеют
        канонизировать dict, но не класс ``Hierarchy``.

        Что внутри: ``version``, ``turn``, урезанный ``log`` с признаком
        усечения, все поля ``Realm``/``Duchy``/``Character``, контракты
        (только ``liege_id``/``vassal_id``/``level``), выданные приказы
        (``orders``) и девять полей поселения по каждой провинции.

        Чего здесь НЕТ и почему:

        * ``self.provinces`` целиком. Геометрия (полигоны, центроиды, имена
          соседей, ``troops``) принадлежит мировому слою; ``states.py`` по
          контракту о ней не знает и оперирует любым duck-объектом. Если бы
          мы тащили геометрию в снапшот, иерархия перестала бы переноситься
          в отдельный серверный процесс, а карта и её 149 тестов зависели бы
          от порядка сохранения. Провинции приходят в ``from_state`` параметром.
        * ``_province_duchy``. Производный кэш «индекс провинции -> герцогство»,
          целиком восстанавливается вызовом ``_rebuild_province_index()`` в
          конструкторе. Хранить его — значило бы хранить redundancy, которая
          может разойтись с ``duchies``.
        * ``streams``. ГПСЧ — внешний источник энтропии, а не состояние мира:
          его положение нужно только для продолжения бросков. При загрузке
          чужого снапшота «продолжить броски» всё равно бессмысленно, поэтому
          потоки задаются конструктором.
        * ``action_ledger``. Журнал израсходованных «раз за ход» действий
          обнуляется в ``end_turn``, поэтому в канонической точке сохранения
          (граница хода) он пуст и не несёт информации. ``from_state``
          восстанавливает ``turn``, но не журнал, так что загруженный мир
          получает чистый счёт действий текущего хода. Известный компромисс
          этого решения: сохранение ПОСЕРЕДИНЕ хода вернёт игроку израсходованные
          лимиты (обход через перезагрузку). Плата за честный формат — целый
          класс эксплойтов — несоразмерна, потому что сервер всё равно
          пересчитывает лимиты у себя; когда формат снапшота станет версионируемым
          по-настоящему (а не через ``.get(field, default)``), журнал добавится
          в снапшот вместе с ростом ``STATE_VERSION``.
        * ``linked_general``. Внешняя ссылка на объект из другого слоя
          (генерал армии), которая к тому же меняется каждый ход. Сериализовать
          её нельзя — сломается контракт изоляции модуля.
        * Ничего из ``sim/``. Фолбэк ``repr`` в ``sim/serialization.py``
          закреплён тестами ``test_sim.py``, и править его отсюда нельзя.

        Новые поля этапа 3 (``raised_levy``, ``mercenary_tiers``,
        ``gifts_received``) — обычные поля dataclass, поэтому снапшот по
        Realm/Duchy/Character остаётся полным: любое забытое поле разъехало
        бы хеш после round-trip. ``orders`` устроен так же: это единственный
        новый верхнеуровневый ключ этапа 1.2, и его содержимое — все девять полей
        ``Order``, чтобы ``state_hash`` после round-trip совпал до бита.

        Порядок ключей детерминирован (реестры — по отсортированным id),
        так что ``state_hash`` от двух одинаковых миров совпадает.
        """
        state: Dict[str, object] = {
            "version": STATE_VERSION,
            "turn": self.turn,
            "log": list(self.log[-LOG_KEEP:]),
            "log_truncated": self.log_truncated or len(self.log) > LOG_KEEP,
            "realms": {r.id: {
                "id": r.id,
                "name": r.name,
                "nation": r.nation,
                "ruler_id": r.ruler_id,
                "capital_idx": r.capital_idx,
                "gold": r.gold,
                "prestige": r.prestige,
                "stability": r.stability,
                "crown_authority": r.crown_authority,
                "tax_policy": r.tax_policy,
                "is_player": r.is_player,
                # траты этапа 3: без них мир грузился бы с бесплатным левейсом
                # и без истории наёмников
                "raised_levy": r.raised_levy,
                # копия, а не сам список: снапшот не должен делить его
                # с живым королевством
                "mercenary_tiers": list(r.mercenary_tiers),
            } for r in sorted(self.realms.values(), key=lambda x: x.id)},
            "duchies": {d.id: {
                "id": d.id,
                "name": d.name,
                # de_jure_provinces — tuple: иначе JSON вернул бы список
                # и round-trip тихо сменил бы тип поля.
                "de_jure_provinces": tuple(d.de_jure_provinces),
                "holder_id": d.holder_id,
                # de-факто держатель (этап 2): от него зависит duchy_income,
                # то есть то, что игрок видит в панели герцогства. Без него
                # мир после загрузки считал бы доход по старым de jure правилам.
                "de_facto_holder_id": d.de_facto_holder_id,
                "realm_id": d.realm_id,
                "development": d.development,
                "siege_safety": d.siege_safety,
            } for d in sorted(self.duchies.values(), key=lambda x: x.id)},
            "characters": {c.id: {
                "id": c.id,
                "name": c.name,
                "nation": c.nation,
                # enum как его собственное имя: не полагаемся на реестр
                # register_enum и не тащим служебные теги в формат.
                "rank": c.rank.name,
                "realm_id": c.realm_id,
                "duchy_id": c.duchy_id,
                "province_idx": c.province_idx,
                "gold": c.gold,
                "influence": c.influence,
                "loyalty": c.loyalty,
                "opinion_of_liege": c.opinion_of_liege,
                "contract_level": c.contract_level,
                "martial": c.martial,
                "stewardship": c.stewardship,
                "diplomacy": c.diplomacy,
                "age": c.age,
                "death_age": c.death_age,
                "alive": c.alive,
                "traits": tuple(c.traits),
                "heir": c.heir,
                "landless_turns": c.landless_turns,
                "gifts_received": c.gifts_received,
            } for c in sorted(self.characters.values(), key=lambda x: x.id)},
            "contracts": {vassal_id: {
                "liege_id": c.liege_id,
                "vassal_id": c.vassal_id,
                "level": c.level,
            } for vassal_id, c in sorted(self.contracts.items())},
            # Приказы — состояние, а не история: у приказа есть срок и
            # последствия, поэтому без него мир после загрузки «забыл» бы, что
            # вассал отказался (или что сюзерен ждёт исполнения).
            # enum'ы пишутся ЗНАЧЕНИЕМ, а не именем, как у персонажей: у приказа
            # вид и статус приходят из сети по строке, и ``.name``/``.value``
            # совпадают только у части видов.
            "orders": {order_id: {
                "id": order_id,
                "kind": o.kind.value,
                "issuer_id": o.issuer_id,
                "target_id": o.target_id,
                "turn_issued": o.turn_issued,
                # копия: снапшот не должен делить словарь с живым приказом
                "args": dict(o.args),
                "status": o.status.value,
                "resolved_turn": o.resolved_turn,
                "message": o.message,
            } for order_id, o in sorted(self.orders.items())},
            # Кризисы престола (этап 4) — состояние, а не история: пустой трон
            # обязан быть виден и обязан пережить ``end_turn``. Ключ реестра —
            # id королевства, на королевство ровно одна запись, поэтому реестр
            # не растёт и порядок обхода по отсортированным id детерминирован.
            "succession_crises": {realm_id: {
                "realm_id": c.realm_id,
                # tuple: JSON отдаёт list, и round-trip тихо сменил бы тип
                "candidates": tuple(c.candidates),
                "turn_opened": c.turn_opened,
                "turn_limit": c.turn_limit,
                "ruler_id": c.ruler_id,
                "resolved_turn": c.resolved_turn,
            } for realm_id, c in sorted(self.succession_crises.items())},
            "counties": {
                idx: {name: getattr(p, name, default)
                      for name, default in COUNTY_FIELD_DEFAULTS.items()}
                for idx, p in enumerate(self.provinces)
            },
        }
        return state

    def state_fingerprint(self) -> str:
        """Хеш состояния мира. Единственная точка хеширования иерархии.

        Именно ``state_hash(self.to_state())``, а НЕ ``state_hash(self)``:
        ``Hierarchy`` не dataclass, поэтому ``canonical`` уходит в
        ``repr(obj)``, а ``repr`` содержит адрес памяти — два одинаковых
        мира получили бы разные хеши. См. докстринг модуля.
        """
        return state_hash(self.to_state())

    @staticmethod
    def from_state(state: Dict[str, object], provinces: Sequence,
                   streams: Optional[NamedStreams] = None) -> "Hierarchy":
        """Восстановить иерархию из снапшота ``to_state()``.

        ``provinces`` — внешний мир: список тех же duck-объектов, что и при
        сохранении. Иерархия не создаёт и не копирует провинции, а только
        переносит на них девять полей поселения. Геометрия, владельцы и
        войска остаются такими, какими были в мировом слое.

        Все поля читаются через ``.get(field, default)``: старый или
        частично заполненный снапшот обязан загружаться, а не падать. Отсюда
        же дефолты берутся у самих dataclass — источник правды один.

        enum'ы восстанавливаются ЯВНО (``TitleRank(...)`` / ``Tier(...)``), а
        не через реестр ``sim.serialization``: так восстановление не зависит
        от того, был ли импортирован модуль с ``register_enum``. Ключи
        ``counties`` приходят из JSON строками — приводим к ``int``.
        """
        realms: Dict[str, Realm] = {}
        for realm_id, data in dict(state.get("realms") or {}).items():
            data = dict(data)
            realms[realm_id] = Realm(
                id=data.get("id", realm_id),
                name=data.get("name", realm_id),
                nation=data.get("nation", "neutral"),
                ruler_id=data.get("ruler_id"),
                capital_idx=data.get("capital_idx"),
                gold=data.get("gold", 500),
                prestige=data.get("prestige", 0),
                stability=data.get("stability", 100),
                crown_authority=data.get("crown_authority", 2),
                tax_policy=data.get("tax_policy", 0),
                is_player=bool(data.get("is_player", False)),
                # старый снапшот без трат этапа 3 читается как «ничего не поднято»
                raised_levy=as_int(data.get("raised_levy")) or 0,
                # список, а не ссылка на поле снапшота: JSON отдаёт list,
                # а мусор в нём обязан игнорироваться, а не ронять загрузку
                mercenary_tiers=clean_mercenary_tiers(data.get("mercenary_tiers")),
            )

        duchies: Dict[str, Duchy] = {}
        for duchy_id, data in dict(state.get("duchies") or {}).items():
            data = dict(data)
            duchies[duchy_id] = Duchy(
                id=data.get("id", duchy_id),
                name=data.get("name", duchy_id),
                # обратно в tuple: JSON отдаёт list
                de_jure_provinces=tuple(data.get("de_jure_provinces") or ()),
                holder_id=data.get("holder_id"),
                # старый снапшот без de-факто держателя читается как «ничья»:
                # так честнее, чем молчаливый пересчёт по текущей карте —
                # загруженный мир должен совпасть с сохранённым по хешу.
                de_facto_holder_id=data.get("de_facto_holder_id"),
                realm_id=data.get("realm_id"),
                development=data.get("development", 1),
                siege_safety=data.get("siege_safety", 0),
            )

        characters: Dict[str, Character] = {}
        for ch_id, data in dict(state.get("characters") or {}).items():
            data = dict(data)
            raw_rank = data.get("rank", TitleRank.BARON.name)
            if isinstance(raw_rank, TitleRank):
                rank = raw_rank
            else:
                try:
                    rank = TitleRank[raw_rank]
                except KeyError:
                    try:
                        rank = TitleRank(raw_rank)
                    except ValueError:
                        rank = TitleRank.BARON
            traits = data.get("traits") or ()
            if isinstance(traits, str):
                traits = (traits,)
            characters[ch_id] = Character(
                id=data.get("id", ch_id),
                name=data.get("name", ch_id),
                nation=data.get("nation", "neutral"),
                rank=rank,
                realm_id=data.get("realm_id"),
                duchy_id=data.get("duchy_id"),
                province_idx=data.get("province_idx"),
                gold=data.get("gold", 0),
                influence=data.get("influence", 10),
                loyalty=data.get("loyalty", 70),
                opinion_of_liege=data.get("opinion_of_liege", 20),
                contract_level=data.get("contract_level", 2),
                martial=data.get("martial", 5),
                stewardship=data.get("stewardship", 5),
                diplomacy=data.get("diplomacy", 5),
                age=data.get("age", 30),
                # старый снапшот без личного порога читается как «умрёт в 80»
                death_age=as_int(data.get("death_age")) or CHARACTER_DEATH_AGE,
                alive=bool(data.get("alive", True)),
                # обратно в tuple: JSON отдаёт list
                traits=tuple(traits),
                heir=data.get("heir"),
                landless_turns=data.get("landless_turns", 0),
                gifts_received=as_int(data.get("gifts_received")) or 0,
            )

        contracts: Dict[str, VassalContract] = {}
        for vassal_id, data in dict(state.get("contracts") or {}).items():
            data = dict(data)
            contracts[vassal_id] = VassalContract(
                liege_id=data.get("liege_id", ""),
                vassal_id=data.get("vassal_id", vassal_id),
                level=data.get("level", 2),
            )

        orders: Dict[str, Order] = {}
        for raw_id, data in dict(state.get("orders") or {}).items():
            data = dict(data)
            kind = order_kind_of(data.get("kind"))
            if kind is None:
                # приказ неизвестного вида исполнить нечем и нечем показать в
                # UI: пропускаем запись целиком. Старый снапшот без ``orders``
                # тоже сюда попадает — просто с пустым словарём.
                continue
            try:
                status = OrderStatus(data.get("status", OrderStatus.PENDING.value))
            except ValueError:
                status = OrderStatus.PENDING
            # id приводим к строке: JSON уже отдал строки, а вот
            # hand-made снапшот мог иметь числовой ключ — и тогда он разошёлся бы
            # с ``to_state`` по типу ключа, а счётчик id сбился бы.
            order_id = str(data.get("id") or raw_id)
            orders[order_id] = Order(
                id=order_id,
                kind=kind,
                issuer_id=str(data.get("issuer_id") or ""),
                target_id=str(data.get("target_id") or ""),
                turn_issued=as_int(data.get("turn_issued")) or 0,
                args=clean_order_args(data.get("args")),
                status=status,
                resolved_turn=as_int(data.get("resolved_turn")),
                message=str(data.get("message") or ""),
            )

        crises: Dict[str, SuccessionCrisis] = {}
        for raw_id, data in dict(state.get("succession_crises") or {}).items():
            data = dict(data)
            realm_id = str(data.get("realm_id") or raw_id)
            raw_candidates = data.get("candidates") or ()
            if isinstance(raw_candidates, str):
                raw_candidates = (raw_candidates,)
            crises[realm_id] = SuccessionCrisis(
                realm_id=realm_id,
                # обратно в tuple: JSON отдаёт list
                candidates=tuple(str(c) for c in raw_candidates),
                turn_opened=as_int(data.get("turn_opened")) or 0,
                turn_limit=as_int(data.get("turn_limit")) or 0,
                ruler_id=data.get("ruler_id"),
                resolved_turn=as_int(data.get("resolved_turn")),
            )

        hierarchy = Hierarchy(provinces, duchies, realms, characters, contracts,
                              streams=streams, orders=orders,
                              succession_crises=crises)

        for raw_idx, data in dict(state.get("counties") or {}).items():
            try:
                idx = int(raw_idx)
            except (TypeError, ValueError):
                continue
            if not 0 <= idx < len(provinces):
                continue
            province = provinces[idx]
            # только белый список полей: битый снапшот не должен уметь
            # дописать в провинцию произвольный атрибут
            for name, default in COUNTY_FIELD_DEFAULTS.items():
                setattr(province, name, dict(data).get(name, default))

        hierarchy.turn = int(state.get("turn", 1))
        log = state.get("log") or []
        hierarchy.log = list(log)
        # признак усечения берём из снапшота, а не вычисляем заново:
        # иначе состояние, обрезанное при сохранении, после round-trip
        # выглядело бы полным и отличалось хешем от исходного.
        hierarchy.log_truncated = bool(state.get("log_truncated", False))
        # action_ledger намеренно НЕ восстанавливается: журнал лимитов обнуляется
        # в end_turn и в снапшот не входит (см. to_state), поэтому загруженный
        # мир получает чистый счёт действий текущего хода.
        return hierarchy


def _duchy_province_map() -> Dict[int, str]:
    """Индекс провинции -> id герцогства (de jure)."""
    mapping: Dict[int, str] = {}
    for duchy_id, _name, provs in DUCHY_DEFS:
        for idx in provs:
            mapping[idx] = duchy_id
    return mapping


def build_default_hierarchy(provinces: Sequence,
                           streams: Optional[NamedStreams] = None) -> Hierarchy:
    """Строит иерархию по текущей карте: 3 королевства, 6 герцогов, 12 баронов.

    Провинции получают ``duchy_id``, ``hearths``, ``prosperity``, ``loyalty``,
    ``security``, ``development``, ``fort_level``, ``garrison`` и ``villages``
    с дефолтами — старые тесты, читающие ``owner``/``region_type``,
    продолжают работать.

    ``fort_level`` выставляется как 0/1/2 (деревня/город/столица), и именно
    он задаёт потолок гарнизона в ``garrison_cap``: до этапа 0.4 поле было
    заполнено, но не читалось нигде, то есть было мёртвым. Стартовый
    гарнизон (0/100/200) ровно упирается в этот потолок.

    ``streams`` — симметрично конструктору ``Hierarchy``: ``None`` означает
    ``new_streams(HIERARCHY_DEFAULT_SEED)``. Параметр нужен для явной
    фиксации зерна в тестах и реплеях; на стартовое состояние он не влияет,
    потому что ни одна фаза хода ГПСЧ не трогает.
    """
    duchies: Dict[str, Duchy] = {}
    realms: Dict[str, Realm] = {}
    characters: Dict[str, Character] = {}
    contracts: Dict[str, VassalContract] = {}

    for realm_id, realm_name, nation, capital in REALM_DEFS:
        realms[realm_id] = Realm(id=realm_id, name=realm_name, nation=nation,
                                 capital_idx=capital, is_player=(nation == "blue"))

    for duchy_id, duchy_name, provs in DUCHY_DEFS:
        holder = next((d[0] for d in DUKE_DEFS if d[3] == duchy_id), None)
        nation = next((d[2] for d in DUKE_DEFS if d[3] == duchy_id), "neutral")
        realm_id = next((r.id for r in realms.values() if r.nation == nation), None)
        duchies[duchy_id] = Duchy(id=duchy_id, name=duchy_name,
                                  de_jure_provinces=tuple(provs),
                                  holder_id=holder, realm_id=realm_id)

    for king_id, name, nation, realm_id in KING_DEFS:
        characters[king_id] = Character(id=king_id, name=name, nation=nation,
                                        rank=TitleRank.KING, realm_id=realm_id,
                                        gold=400, influence=40, age=44)
        realms[realm_id].ruler_id = king_id

    for duke_id, name, nation, duchy_id, provs in DUKE_DEFS:
        realm_id = next(r.id for r in realms.values() if r.nation == nation)
        characters[duke_id] = Character(id=duke_id, name=name, nation=nation,
                                        rank=TitleRank.DUKE, realm_id=realm_id,
                                        duchy_id=duchy_id, gold=150, influence=25, age=38)
        # сюзерен герцога — король ИМЕННО ЕГО королевства
        liege_id = realms[realm_id].ruler_id or ""
        contracts[duke_id] = VassalContract(liege_id=liege_id, vassal_id=duke_id, level=2)

    for baron_id, name, nation, duchy_id, prov_idx in BARON_DEFS:
        duke = characters.get(next((d[0] for d in DUKE_DEFS if d[3] == duchy_id), ""))
        characters[baron_id] = Character(id=baron_id, name=name, nation=nation,
                                         rank=TitleRank.BARON, duchy_id=duchy_id,
                                         province_idx=prov_idx, gold=50, influence=10,
                                         age=30)
        if duke:
            contracts[baron_id] = VassalContract(liege_id=duke.id, vassal_id=baron_id,
                                                 level=2)

    # инициализация поселений: население и лояльность зависят от типа
    duchy_of_province = _duchy_province_map()
    for idx, p in enumerate(provinces):
        defaults = {
            "duchy_id": duchy_of_province.get(idx),
            "hearths": HEARTHS_VILLAGE,
            "prosperity": 20,
            "loyalty": 70,
            "security": 10,
            "development": 1,
            "fort_level": 0,
            "garrison": 0,
            "villages": 2,
        }
        for field_name, value in defaults.items():
            if not hasattr(p, field_name):
                setattr(p, field_name, value)
        p.duchy_id = duchy_of_province.get(idx)
        # столицы и города богаче и лучше защищены
        region_type = getattr(p, "region_type", None)
        tier_name = getattr(region_type, "name", "")
        if tier_name == "CAPITAL":
            p.hearths = max(p.hearths, HEARTHS_CAPITAL)
            p.prosperity = max(p.prosperity, 35)
            p.fort_level = 2
            p.garrison = 200
        elif tier_name == "CITY":
            p.hearths = max(p.hearths, HEARTHS_CITY)
            p.prosperity = max(p.prosperity, 25)
            p.fort_level = 1
            p.garrison = 100

    hierarchy = Hierarchy(provinces, duchies, realms, characters, contracts, streams=streams)
    # личный возраст смерти раздаётся по id (детерминированно): поколения должны
    # перемежаться, иначе все бароны одной нации умрут в один ход и наследовать
    # будет некому — см. CHARACTERS_DEATH_AGE_SPREAD
    for character_id in sorted(characters):
        characters[character_id].death_age = character_death_age(character_id)
    # de-факто держатели вычисляются один раз здесь, а не лениво по чтению:
    # от них зависит duchy_income, а значит и панель герцогства уже на первом
    # кадре. Нулевые значения в provinces по этому моменту уже расставлены.
    hierarchy.recompute_de_facto_holders()
    return hierarchy


def auto_inherit(hierarchy: Hierarchy) -> List[str]:
    """Разобрать титулы всех, кто уже мёртв (обратная совместимость).

    Историческая функция была написана и НЕ ВЫЗЫВАЛАСЬ ни одной строкой кода:
    до этапа 4 в игре не умирал никто, а значит не наследовалось ничего. Теперь
    ею пользуется ``Hierarchy.tick_characters`` — то есть это тот же самый
    разбор, а не второй, расходящийся с ним.

    Оставлена внешней функцией, а не методом, потому что на неё могли ссылаться
    ``world_map.py``/``campaigns.py``; реализация переехала в
    ``Hierarchy.settle_deaths``, где живут престол, герцогство, графство и
    контракты вместе. Новая логика наследования (ранг преемника, де-факто
    держатель герцогства, пересчёт контракта) — там же.
    """
    dead = [ch for ch in sorted(hierarchy.characters.values(), key=lambda c: c.id)
            if not ch.alive]
    return hierarchy.settle_deaths(dead)
